def vector(identifier: str, op: str, a: int, b: int = 0, c: int = 0, *, category: str) -> dict:
  return {
    "id": identifier,
    "op": op,
    "a": f"0x{a:08x}",
    "b": f"0x{b:08x}",
    "c": f"0x{c:08x}",
    "category": category,
  }


def evaluate(item: dict) -> FPResult:
  op = item["op"]
  a, b, c = (int(item[name], 16) for name in ("a", "b", "c"))
  if op == "fma":
    return fma_f32_rne(a, b, c)
  if op == "add":
    return add_f32_rne(a, b)
  if op == "mul":
    return mul_f32_rne(a, b)
  if op == "bf16":
    return f32_to_bf16_rne(a)
  if op == "i32":
    return f32_to_i32_rne(a)
  raise ValueError(f"unknown primitive operation {op!r}")


def result_dict(op: str, result: FPResult | tuple[int, int]) -> dict:
  bits, flags = (result.bits, result.flags) if isinstance(result, FPResult) else result
  return {"bits": f"0x{bits:0{4 if op == 'bf16' else 8}x}", "flags": f"0x{flags:02x}"}



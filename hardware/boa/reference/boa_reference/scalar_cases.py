def special_cases() -> Iterable[dict]:
  for op, arity in (("fma", 3), ("add", 2), ("mul", 2), ("bf16", 1), ("i32", 1)):
    for index, operands in enumerate(itertools.product(SPECIAL_WORDS, repeat=arity)):
      padded = (*operands, 0, 0)
      yield vector(f"S-{op}-{index:05d}", op, *padded[:3], category="special-matrix")


def bf16_boundary_cases() -> Iterable[dict]:
  index = 0
  for sign, exponent, top, low in itertools.product(
    (0, 1),
    (0, 1, 2, 63, 126, 127, 128, 253, 254),
    (0, 1, 2, 63, 64, 125, 126, 127),
    (0, 0x7FFF, 0x8000, 0x8001, 0xFFFF),
  ):
    bits = (sign << 31) | (exponent << 23) | (top << 16) | low
    yield vector(f"B-bf16-{index:04d}", "bf16", bits, category="bf16-boundary")
    index += 1


def scalar_vectors(seed: int, random_cases: int = 1024, *, specials_only: bool = False) -> list[dict]:
  if type(seed) is not int or type(random_cases) is not int or random_cases < 0:
    raise ValueError("seed and nonnegative random_cases must be integers")
  candidates = [*directed_cases(), *special_cases(), *bf16_boundary_cases()]
  if not specials_only:
    rng = random.Random(seed)
    for op in OPERATIONS:
      for index in range(random_cases):
        a, b, c = (rng.getrandbits(32) for _ in range(3))
        if op == "fma" and index % 2 == 0:
          a, b = rng.getrandbits(16) << 16, rng.getrandbits(16) << 16
        if op in ("bf16", "i32"):
          b = 0
        if op != "fma":
          c = 0
        candidates.append(vector(f"R-{op}-{index:05d}", op, a, b, c, category="seeded-random"))
  # Keep the explicit analytic check when it overlaps a Cartesian-matrix row.
  seen = set()
  result = []
  for item in candidates:
    key = tuple(item[name] for name in ("op", "a", "b", "c"))
    if key not in seen:
      seen.add(key)
      result.append(item)
  return result


def primitive_checks() -> list[tuple[str, bool, str]]:
  checks = []
  for item in directed_cases():
    observed = result_dict(item["op"], evaluate(item))
    checks.append(
      (
        item["id"],
        observed == item["analytic_expected"],
        f"observed={observed}, expected={item['analytic_expected']}",
      )
    )
  return checks

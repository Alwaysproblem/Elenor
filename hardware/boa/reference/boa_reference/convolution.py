"""Independent NCHW/OIHW direct-convolution reference (bf16_fp32_mac_rne_v1).

The answer path uses direct convolution index loops ONLY: it never calls
the Matmul oracle and never reads the exported im2col matrix to produce
C.  K is flattened exactly as (ic, kh, kw) and Matmul rows are
(n, oh, ow); C is row-major [N*OH*OW, O].  The per-block AM schedule is
identical to the Matmul profile with an implicit INIT (first
contribution block overwrites; K == 0 initializes +0) and one FINAL
epilogue over the whole [M, O] matrix.

Spatial padding supplies real +0 BF16 operands that DO execute MACs, so
0 x Inf yields NaN.  This is deliberately different from masked/tail
lanes in the Matmul oracle, which bypass arithmetic entirely; conv has
no mask and every lane at 0..K-1 is active.

Output geometry uses the declared floor formula
OH = max(0, (H + pad_top + pad_bottom - ((KH-1)*dh + 1)) // sh + 1) and
likewise for OW. If the effective kernel does not fit the padded input,
the result is empty, with no MAC and no contribution blocks.

The exported A matrix (im2col layout, row-major [M, K]) and the B layout
([K, O], the OIHW weights reindexed by the declared K order) are
generated by independent index loops for P08 byte-layout checking; they
never feed the answer path.

Traffic numbers are logical one-materialization payload counts, spelled
out in _TRAFFIC_ASSUMPTIONS.  They are cross-checked at runtime against
a direct in-loop count of in-bounds patch elements and raise on any
mismatch.  They are not physical burst or cycle lower bounds.
"""

from __future__ import annotations

from collections.abc import Sequence

from . import scalar
from .epilogue import (
  Epilogue,
  apply_epilogue,
  json_trace,
  output_dtype_width,
  result_dtype,
  validate_epilogue,
)

_PLUS_ZERO_BF16 = 0x0000
_PLUS_ZERO_F32 = 0x00000000

_TRAFFIC_ASSUMPTIONS = (
  "Logical one-materialization payload counts: every valid patch element is "
  "read once from the input feature map, every padding position contributes "
  "one zero BF16 element written into the expanded matrix, the expanded A "
  "matrix is written once by im2col and read once by the Matmul, B is read "
  "once as a full KxO pass, and the output is written once in the epilogue "
  "dtype.  No reuse, cache retention, L2/L1 overlap, split-K folding or "
  "multi-batch sharing is credited, so these are not physical burst or "
  "cycle lower bounds."
)


def _require_index(value, name, minimum):
  if isinstance(value, bool) or not isinstance(value, int):
    raise TypeError(f"{name} must be an int")
  if value < minimum:
    raise ValueError(f"{name} out of range: {value!r}")


def _check_shape(shape, name, min_kernel=0):
  if isinstance(shape, (str, bytes)) or not isinstance(shape, (list, tuple)):
    raise TypeError(f"{name} must be a 4-tuple of ints")
  if len(shape) != 4:
    raise ValueError(f"{name} must have 4 entries")
  for index, value in enumerate(shape):
    _require_index(value, f"{name}[{index}]", 0)
  if shape[2] < min_kernel or shape[3] < min_kernel:
    raise ValueError(f"{name} spatial kernel sizes must be >= {min_kernel}")
  return tuple(shape)


def _check_pair(pair, name, minimum):
  if isinstance(pair, (str, bytes)) or not isinstance(pair, (list, tuple)):
    raise TypeError(f"{name} must be a pair of ints")
  if len(pair) != 2:
    raise ValueError(f"{name} must have 2 entries")
  for index, value in enumerate(pair):
    _require_index(value, f"{name}[{index}]", minimum)
  return (pair[0], pair[1])


def _check_padding(padding):
  if isinstance(padding, (str, bytes)) or not isinstance(padding, (list, tuple)):
    raise TypeError("padding must be a 4-tuple (top, bottom, left, right)")
  if len(padding) != 4:
    raise ValueError("padding must have 4 entries (top, bottom, left, right)")
  for index, value in enumerate(padding):
    _require_index(value, f"padding[{index}]", 0)
  return tuple(padding)


def _require_words(words, length, name):
  if isinstance(words, (str, bytes)) or not isinstance(words, (list, tuple)):
    raise TypeError(f"{name} must be a sequence of BF16 bit patterns")
  if len(words) != length:
    raise ValueError(f"{name} has {len(words)} words but {length} are required")
  for index, word in enumerate(words):
    if isinstance(word, bool) or not isinstance(word, int):
      raise TypeError(f"{name}[{index}] must be an integer bit pattern")
    if not 0 <= word <= 0xFFFF:
      raise ValueError(f"{name}[{index}] out of range: {word!r}")


def _hex16_list(words):
  return [f"0x{v:04x}" for v in words]


def _hex32_list(words):
  return [f"0x{v:08x}" for v in words]


def _word_bytes(words, width):
  return b"".join(v.to_bytes(width, "little") for v in words).hex()


def conv2d_reference(
  x: Sequence[int],
  weights: Sequence[int],
  shape: tuple[int, int, int, int],
  kernel: tuple[int, int, int, int],
  stride: tuple[int, int] = (1, 1),
  padding: tuple[int, int, int, int] = (0, 0, 0, 0),
  dilation: tuple[int, int] = (1, 1),
  tile_k: int = 8,
  epilogue: Epilogue | None = None,
) -> dict:
  """Exact BF16 direct convolution; returns a JSON-ready result dict.

  Direct-conv answer path: per output element the implicit INIT/ADD block
  schedule runs over K = C*KH*KW flattened as (ic, kh, kw); padded
  positions supply real +0 operands and execute their MAC.  The exported
  A/B matrices and the analytic traffic counts never feed the answer.
  """
  n, c, h, w = _check_shape(shape, "shape")
  o, kc, kh, kw = _check_shape(kernel, "kernel", min_kernel=1)
  if kc != c:
    raise ValueError(f"kernel channel count {kc} does not match shape {c}")
  sh, sw = _check_pair(stride, "stride", 1)
  dh, dw = _check_pair(dilation, "dilation", 1)
  pt, pb, pl, pr = _check_padding(padding)
  _require_index(tile_k, "tile_k", 1)
  _require_words(x, n * c * h * w, "x")
  _require_words(weights, o * c * kh * kw, "weights")
  epilogue = Epilogue() if epilogue is None else epilogue
  validate_epilogue(epilogue, o)

  ekh = (kh - 1) * dh + 1
  ekw = (kw - 1) * dw + 1
  oh = max(0, (h + pt + pb - ekh) // sh + 1)
  ow = max(0, (w + pl + pr - ekw) // sw + 1)
  m_rows = n * oh * ow
  k_total = c * kh * kw
  blocks = [(start, min(start + tile_k, k_total)) for start in range(0, k_total, tile_k)]

  # Exported im2col A matrix and direct in-loop counting; never used for C.
  a_flat: list[int] = []
  valid_direct = 0
  for n_i in range(n):
    for oh_i in range(oh):
      base_h = oh_i * sh - pt
      for ow_i in range(ow):
        base_w = ow_i * sw - pl
        for c_i in range(c):
          for kh_i in range(kh):
            h_in = base_h + kh_i * dh
            row_ok = 0 <= h_in < h
            for kw_i in range(kw):
              w_in = base_w + kw_i * dw
              if row_ok and 0 <= w_in < w:
                a_flat.append(x[((n_i * c + c_i) * h + h_in) * w + w_in])
                valid_direct += 1
              else:
                a_flat.append(_PLUS_ZERO_BF16)

  # Direct convolution answer path over the original input words only.
  c_flat: list[int] = []
  mac_count = 0
  am_add_count = 0
  initialization_count = 0
  for n_i in range(n):
    for oh_i in range(oh):
      base_h = oh_i * sh - pt
      for ow_i in range(ow):
        base_w = ow_i * sw - pl
        for o_i in range(o):
          am_word = None
          for start, end in blocks:
            p = _PLUS_ZERO_F32
            for k_index in range(start, end):
              c_i = k_index // (kh * kw)
              rem = k_index % (kh * kw)
              kh_i = rem // kw
              kw_i = rem % kw
              h_in = base_h + kh_i * dh
              w_in = base_w + kw_i * dw
              if 0 <= h_in < h and 0 <= w_in < w:
                a_bits = x[((n_i * c + c_i) * h + h_in) * w + w_in]
              else:
                # Real +0 padding operand; this MAC deliberately executes
                # so that 0 x Inf produces NaN exactly like hardware.
                a_bits = _PLUS_ZERO_BF16
              b_bits = weights[((o_i * c + c_i) * kh + kh_i) * kw + kw_i]
              p = scalar.fma_f32_rne(scalar.bf16_to_f32(a_bits), scalar.bf16_to_f32(b_bits), p).bits
              mac_count += 1
            if am_word is None:
              am_word = p
              initialization_count += 1
            else:
              am_word = scalar.add_f32_rne(am_word, p).bits
              am_add_count += 1
          if am_word is None:
            am_word = _PLUS_ZERO_F32
            initialization_count += 1
          c_flat.append(am_word)

  applied = apply_epilogue(c_flat, m_rows, o, epilogue)
  dtype_width = output_dtype_width(result_dtype(applied.trace))
  output_bits = [f"0x{v:0{2 * dtype_width}x}" for v in applied.output_bits]
  output_hex = applied.output_bytes.hex()
  epilogue_trace = json_trace(applied.trace)

  valid_rows = sum(1 for oh_i in range(oh) for kh_i in range(kh) if 0 <= oh_i * sh - pt + kh_i * dh < h)
  valid_cols = sum(1 for ow_i in range(ow) for kw_i in range(kw) if 0 <= ow_i * sw - pl + kw_i * dw < w)
  valid_analytic = n * c * valid_rows * valid_cols
  expanded = m_rows * k_total
  if valid_direct != valid_analytic:
    raise ValueError(f"analytic traffic {valid_analytic!r} does not match direct counting {valid_direct!r}")
  traffic = {
    "valid_patch_elements": valid_analytic,
    "expanded_elements": expanded,
    "padding_zero_elements": expanded - valid_analytic,
    "valid_patch_read_bytes": 2 * valid_analytic,
    "padding_zero_bytes": 2 * (expanded - valid_analytic),
    "im2col_write_bytes": 2 * expanded,
    "matmul_a_read_bytes": 2 * expanded,
    "matmul_b_read_bytes": 2 * k_total * o,
    "output_bytes": m_rows * o * dtype_width,
    "assumptions": _TRAFFIC_ASSUMPTIONS,
  }
  traffic_direct = {
    "valid_patch_elements": valid_direct,
    "expanded_elements": expanded,
    "padding_zero_elements": expanded - valid_direct,
  }

  b_flat = [0] * (k_total * o)
  for o_i in range(o):
    for k_index in range(k_total):
      c_i = k_index // (kh * kw)
      rem = k_index % (kh * kw)
      kh_i = rem // kw
      kw_i = rem % kw
      b_flat[k_index * o + o_i] = weights[((o_i * c + c_i) * kh + kh_i) * kw + kw_i]

  return {
    "in_shape": [n, c, h, w],
    "kernel_shape": [o, c, kh, kw],
    "stride": [sh, sw],
    "padding": [pt, pb, pl, pr],
    "dilation": [dh, dw],
    "tile_k": tile_k,
    "k_flatten_order": "(ic, kh, kw)",
    "out_shape": [n, o, oh, ow],
    "m": m_rows,
    "n": o,
    "k": k_total,
    "c_bits": _hex32_list(c_flat),
    "output_bits": output_bits,
    "output_hex": output_hex,
    "a_bits": _hex16_list(a_flat),
    "a_hex": _word_bytes(a_flat, 2),
    "b_bits": _hex16_list(b_flat),
    "b_hex": _word_bytes(b_flat, 2),
    "mac_count": mac_count,
    "am_add_count": am_add_count,
    "initialization_count": initialization_count,
    "epilogue_trace": epilogue_trace,
    "traffic": traffic,
    "traffic_direct": traffic_direct,
  }

FORBIDDEN_GRANT_TOKENS = (
  "event",
  "event_slot",
  "event_record",
  "event_wait",
  "await_event",
  "completion_event",
  "event_table",
  "event_reap",
)

WRAPAROUND_COUNTERS = (
  "slot_generation",
  "ctx_epoch",
  "request_seq",
  "request_id",
  "lease_handle",
  "chain_id",
  "step_seq",
  "mem_req_id",
  "step_token",
)


def lint_schema(schema: dict) -> list[str]:
  """Static invariants from plan/P10 section 4; an empty list means PASS."""
  problems: list[str] = []
  model = parse_schema(schema)

  abi, frame = schema["abi"], schema["frame"]
  if (frame["version_bits"], frame["kind_bits"], frame["length_bits"]) != (8, 8, 16):
    problems.append("frame: header layout must be 8/8/16 bits")
  if frame["byte_order"] != "little" or frame.get("magic") != "0x4250":
    problems.append("frame: must be little-endian with magic 0x4250")
  if abi["wire_version_int"] != 0 or abi["wire_version"] != "v0":
    problems.append("abi: this schema freezes wire v0 only")

  kinds: dict[int, str] = {}
  for name, message in model["messages"].items():
    if message.kind_id in kinds:
      problems.append(f"message {name}: kind {message.kind_id} already used by {kinds[message.kind_id]}")
    kinds[message.kind_id] = name

  grant = schema["grant"]
  for precondition in grant["preconditions"]:
    tokens = {precondition["id"].lower(), precondition["kind"].lower()}
    if tokens & set(FORBIDDEN_GRANT_TOKENS):
      problems.append(
        f"grant: precondition {precondition['id']!r} lists an event slot as a"
        " grantable or waitable resource; completion_token is reference-only"
      )
  token = grant["completion_token"]
  if token.get("role") != "reference_only" or token.get("never_a_grant_resource") is not True:
    problems.append("grant: completion_token must be reference_only and never a grant resource")
  for message in model["messages"].values():
    for field in message.fields:
      if field.name == "completion_token" and field.role != "reference_only":
        problems.append(f"message {message.name}: completion_token must be reference_only")

  for name, spec in schema["capacities"].items():
    explicit = (
      "value" in spec
      or ("default" in spec and "legal_range" in spec)
      or (spec.get("status") == "reserved" and "legal_range" in spec and "owner" in spec)
      or spec.get("domain") == "software_model"
    )
    if not explicit:
      problems.append(
        f"capacities.{name}: needs an explicit value, a default plus legal_range,"
        f" a reserved owner plus legal_range, or the software_model domain marker"
        f" (got keys {sorted(spec)})"
      )

  wraparound = schema["wraparound"]
  for counter in WRAPAROUND_COUNTERS:
    spec = wraparound.get(counter)
    if not spec:
      problems.append(f"wraparound: missing rule for counter {counter}")
      continue
    if not {"width", "rule", "quiescence", "validated_by"} <= set(spec):
      problems.append(f"wraparound.{counter}: needs width/rule/quiescence/validated_by")
    quiescence = spec.get("quiescence", "").lower()
    wraps = "wrap" in spec.get("rule", "").lower()
    if wraps and "quiesc" not in quiescence and "forbidden" not in quiescence:
      problems.append(f"wraparound.{counter}: wrap without a quiescence condition")
  if "no_width_escape" not in wraparound:
    problems.append("wraparound: missing the no_width_escape statement")

  serialized: set[str] = set()
  for struct in list(model["structs"].values()) + list(model["messages"].values()):
    serialized |= {field.name for field in struct.fields}
    if struct.union:
      for fields in struct.union["variants"].values():
        serialized |= {spec["name"] for spec in fields}
  serialized |= {"enables"}

  submit = model["messages"]["SUBMIT_STEP"]
  usage = [field for field in submit.fields if field.name == "input_usage_handles"]
  if not usage or usage[0].type != "list:struct:AllocationRef":
    problems.append(
      "typed fields: SUBMIT_STEP.input_usage_handles must be a list of typed"
      " AllocationRef usage references, not opaque integers"
    )
  if "AllocationRef" not in model["structs"]:
    problems.append("typed fields: AllocationRef struct is required")
  if not any(field.name == "transpose" for field in submit.fields):
    problems.append("typed fields: SUBMIT_STEP must serialize the per-step transpose")
  am_request = model["messages"]["AM_REQUEST"]
  chain = [field for field in am_request.fields if field.name == "chain_config"]
  if not chain or chain[0].ref_name != "EpilogueConfig":
    problems.append("typed fields: AM_REQUEST must serialize the epilogue parameter block")
  epilogue_fields = {field.name for field in model["structs"]["EpilogueConfig"].fields}
  if not {"bias", "scale", "relu", "clip", "quant"} <= epilogue_fields:
    problems.append("typed fields: EpilogueConfig must carry all per-stage parameters")
  for group_name, grouped in schema["descriptor_groups"].items():
    if not isinstance(grouped, dict):
      continue
    entries = grouped.get("fields", [])
    if entries and not any(entry in serialized for entry in entries):
      problems.append(f"descriptor_groups.{group_name}: fields {entries} are not serialized")

  capacities = schema["capacities"]
  slot_capacity = capacities["am_slot_capacity_bytes"]
  slot_max = (
    slot_capacity["value"]
    if isinstance(slot_capacity.get("value"), int)
    else slot_capacity["legal_range"][1]
  )
  expected_ranges = {
    ("AM_REQUEST", "bundle_slots"): [1, capacities["am_slots_per_context"]["value"]],
    ("AM_REQUEST", "logical_am"): [0, 1],
    ("AM_REQUEST", "byte_count"): [0, slot_max],
    ("AM_REQUEST", "ctx_id"): [0, capacities["contexts_per_tile"]["legal_range"][1] - 1],
    ("AM_GRANTED", "bound_engine"): [0, capacities["engines_per_tile"]["legal_range"][1] - 1],
    ("AM_GRANTED", "group"): [0, capacities["am_group_count"]["value"] - 1],
    ("AM_GRANTED", "slot_index"): [0, capacities["am_slots_per_group"]["value"] - 1],
  }
  for (message_name, field_name), expect in expected_ranges.items():
    field = next(f for f in model["messages"][message_name].fields if f.name == field_name)
    if field.range != expect:
      problems.append(
        f"field ranges: {message_name}.{field_name} range {field.range} disagrees"
        f" with the frozen capacity/width {expect}"
      )
  return problems



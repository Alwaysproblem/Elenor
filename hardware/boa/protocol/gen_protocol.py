  e = L.append
  e(f"// {GENERATOR_NOTE}")
  e("package boa.protocol")
  e("")
  e("object BoaProtocol {")
  e(f"  final val WireVersion: Int = {schema['abi']['wire_version_int']}")
  e("  final val Magic0: Int = 0x42")
  e("  final val Magic1: Int = 0x50")
  e("  final val FrameHeaderBytes: Int = 5")

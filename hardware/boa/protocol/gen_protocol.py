  e("    def u8(field: String): Int = { need(1, field); val v = buf(pos) & 0xff; pos += 1; v }")
  e("    def i8(field: String): Int = { val v = u8(field); if (v >= 0x80) v - 0x100 else v }")
  e("    private def int(width: Int, field: String, signed: Boolean): Long = {")
  e("      need(width, field)")
  e("      var v = 0L")

  e("    def u32(value: Long): Unit = {")
  e("      var v = value")
  e("      var i = 0")
  e("      while (i < 4) { buffer += (v & 0xff).toByte; v >>= 8; i += 1 }")
  e("    }")
  e("    def i32(value: Int): Unit = u32(value.toLong & 0xffffffffL)")
  e("    def u64(value: Long): Unit = {")
  e("      var v = value")
  e("      var i = 0")
  e("      while (i < 8) { buffer += (v & 0xff).toByte; v >>= 8; i += 1 }")
  e("    }")
  e("    def toBytes: Array[Byte] = buffer.result()")
  e("  }")
  e("")

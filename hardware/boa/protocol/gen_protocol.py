#!/usr/bin/env python3
"""Single-source generator for the BOA wire protocol v0 codecs.

Reads the authoritative schema ``hardware/boa/protocol/boa_protocol_v0.json``
and emits three deterministic codecs from it (Python module, Scala object,
C header).  Hand-written message numbering in any downstream language is
forbidden by plan/P10; downstream tasks consume these generated codecs.

The generator also carries the executable schema lint (``lint_schema``) that
the ``boa-protocol`` check target runs against the committed schema and
against negative fixtures.

Wire model (frozen here, all little-endian):

* frame = ``BP`` magic (2B) | version (1B) | kind (1B) | payload length (2B)
  | payload; decoders reject unknown versions/kinds, truncated payloads and
  trailing bytes inside a frame.
* ``EpilogueConfig`` uses a fixed layout: ``n_cols`` (u16), ``enables`` (u8,
  presence bits 0..4, bits 5..7 reserved zero) then the bias words (``n_cols``
  u32), ``scale`` (u32), clip lo/hi (u32 each) and quant inv_scale (u32) +
  zero_point (i8).  Disabled stages serialize canonical zeros; decoders
  reject non-zero words for disabled stages, so decode/encode is canonical
  and byte-identical.
* ``EVT_TAKE`` is a tagged record union discriminated by ``EvtRecordKind``.

Usage:
  gen_protocol.py                # lint + regenerate in place (idempotent)
  gen_protocol.py --check        # exit 1 if the committed files drifted
  gen_protocol.py --out DIR      # write the three files under DIR
  gen_protocol.py --lint         # lint only
"""


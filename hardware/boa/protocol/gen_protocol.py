def generate(schema: dict) -> dict[str, str]:
  model = parse_schema(schema)
  problems = lint_schema(schema)
  if problems:
    raise SchemaError("schema lint failed:\n  " + "\n  ".join(problems))
  return {
    str(OUTPUTS["python"]): emit_python(schema, model),
    str(OUTPUTS["scala"]): emit_scala(schema, model),
    str(OUTPUTS["c"]): emit_c(schema, model),
  }


def sha256_text(text: str) -> str:
  return hashlib.sha256(text.encode("utf-8")).hexdigest()


def main(argv: list[str]) -> int:
  parser = argparse.ArgumentParser(description="Generate the BOA protocol v0 codecs.")
  parser.add_argument("--schema", default=str(SCHEMA_PATH), help="schema JSON path")
  parser.add_argument("--out", default=None, help="write the three files under this root")
  parser.add_argument("--check", action="store_true", help="verify committed outputs match")
  parser.add_argument("--lint", action="store_true", help="lint only, emit nothing")
  args = parser.parse_args(argv)

  try:
    schema = json.loads(Path(args.schema).read_text(encoding="utf-8"))
    problems = lint_schema(schema)
  except (OSError, ValueError) as exc:
    print(f"schema-error: {exc}", file=sys.stderr)
    return 2
  if problems:
    print("schema lint failed:", file=sys.stderr)
    for problem in problems:
      print(f"  - {problem}", file=sys.stderr)
    return 2
  if args.lint:
    print("lint: PASS")
    return 0

  try:
    files = generate(schema)
  except (SchemaError, KeyError, ValueError) as exc:
    print(f"generate-error: {exc}", file=sys.stderr)
    return 2

  if args.out:
    root = Path(args.out)
    for rel in sorted(files):
      write_if_changed(files[rel], root / rel)
      print(f"wrote {root / rel} sha256={sha256_text(files[rel])}")
    return 0

  if args.check:
    drifted = [
      rel
      for rel in sorted(files)
      if not Path(rel).is_file() or Path(rel).read_text(encoding="utf-8") != files[rel]
    ]
    if drifted:
      print("generated outputs drifted; rerun gen_protocol.py:", file=sys.stderr)
      for rel in drifted:
        print(f"  - {rel}", file=sys.stderr)
      return 1
    print("check: generated codecs match the schema")
    return 0

  for rel in sorted(files):
    changed = write_if_changed(files[rel], Path(rel))
    print(f"{'regenerated' if changed else 'unchanged'} {rel} sha256={sha256_text(files[rel])}")
  return 0


if __name__ == "__main__":
  raise SystemExit(main(sys.argv[1:]))

def _py_scalar_type(field: Field) -> str:
  return "bool" if field.type == "bool8" else "int"


def _py_field_type(field: Field) -> str:
  if field.kind == "scalar":
    return _py_scalar_type(field)
  if field.kind == "enum":
    return "int"
  if field.kind == "struct":
    return field.ref_name
  if field.elem_kind == "struct":
    inner = field.elem_ref
  else:
    inner = "int"
  return f"tuple[{inner}, ...]"


def emit_python(schema: dict, model: dict) -> str:
  L: list[str] = []
  e = L.append
  e('"""Generated BOA wire protocol v0 codec (Python).')
  e("")
  e(GENERATOR_NOTE)
  e("")
  e("Single source: hardware/boa/protocol/boa_protocol_v0.json; the Scala and C")
  e("codecs are generated from the same schema.  Decoding is strict: unknown")
  e("versions/kinds/enum values, non-canonical bools, truncated frames, trailing")
  e("bytes, reserved enable bits and non-canonical disabled epilogue stages are")
  e("rejections that name the field.")
  e('"""')
  e("")
  e("from __future__ import annotations")
  e("")
  e("from dataclasses import dataclass")
  e("from typing import Any")
  e("")
  e(f"WIRE_VERSION = {schema['abi']['wire_version_int']}")
  e('MAGIC = b"BP"')
  e("FRAME_HEADER_BYTES = 5")
  caps = schema["capacities"]
  for name in ("am_group_count", "am_slots_per_group", "am_slots_per_context", "am_total_slots_per_tile"):
    e(f"{name.upper()} = {caps[name]['value']}")
  e(f"AM_SLOT_CAPACITY_BYTES_MAX = {caps['am_slot_capacity_bytes']['legal_range'][1]}")
  timing = caps["software_step_timing"]
  e(f"SOFTWARE_RESULT_COMMIT_CYCLES = {timing['result_commit_cycles']}")
  e(f"SOFTWARE_OUTPUT_DRAIN_CYCLES = {timing['output_drain_cycles']}")
  for name, spec in caps.items():
    if spec.get("status") == "reserved":
      e(f"{name.upper()}_LEGAL_RANGE = {tuple(spec['legal_range'])}  # owner {spec['owner']}")
  e("EPILOGUE_EN_BIAS = 0x01")
  e("EPILOGUE_EN_SCALE = 0x02")
  e("EPILOGUE_EN_RELU = 0x04")
  e("EPILOGUE_EN_CLIP = 0x08")
  e("EPILOGUE_EN_QUANT = 0x10")
  e("EPILOGUE_RESERVED_MASK = 0xE0")
  e("")
  e("")
  for ename in sorted(model["enums"]):
    for vname, value in enum_values(model, ename):
      e(f"{enum_const(ename, vname)} = {value}")
    values = enum_values(model, ename)
    valid = ", ".join(str(value) for _, value in values)
    if len(values) > 10:
      wrapped = (",\n    ").join(", ".join(str(item) for _, item in chunk) for chunk in _chunks(values, 8))
      e(f"_{ename.upper()}_VALID = frozenset({{")
      e(f"    {wrapped}")
      e("})")
    else:
      e(f"_{ename.upper()}_VALID = frozenset({{{valid}}})")
    e("")
  dtype = model["enums"]["Dtype"]
  pairs = ", ".join(
    f"{enum_const('Dtype', name)}: {width}" for name, width in dtype["element_bytes"].items()
  )
  e(f"DTYPE_ELEMENT_BYTES = {{{pairs}}}")
  e("")
  e("")
  e("class ProtocolError(ValueError):")
  e('  """Rejection of an encode/decode; ``field`` names the offending field."""')
  e("")
  e("  def __init__(self, field: str, reason: str) -> None:")
  e('    super().__init__(f"{field}: {reason}")')
  e("    self.field = field")
  e("    self.reason = reason")
  e("")
  e("")
  _py_helpers(e)
  for struct in regular_structs(model):
    _py_struct(e, model, struct)
  _py_epilogue(e)
  for variant in [model["variants"][name] for name in sorted(model["variants"])]:
    _py_struct(e, model, variant)
  _py_evt_take(e, model)
  for message in regular_messages(model):
    _py_struct(e, model, message)

  e("MESSAGE_KINDS = {")
  for name in message_names_by_kind(model):
    e(f'  "{name}": {model["messages"][name].kind_id},')
  e("}")
  e("_KIND_CLASSES: dict[int, type] = {")
  for name in message_names_by_kind(model):
    e(f"  {model['messages'][name].kind_id}: {pascal(name)},")
  e("}")
  e("_KIND_NAMES = {")
  for name in message_names_by_kind(model):
    e(f"  {model['messages'][name].kind_id}: {name!r},")
  e("}")
  e("_CLASS_NAMES = {")
  for name in sorted(model["messages"]):
    e(f"  {pascal(name)}: {name!r},")
  e("}")
  e("")
  e("")
  e("def message_name(message) -> str:")
  e("  return _CLASS_NAMES[type(message)]")
  e("")
  e("")
  e("def _frame(kind: int, payload: bytes) -> bytes:")
  e("  header = bytes((0x42, 0x50, WIRE_VERSION, kind)) + len(payload).to_bytes(2, 'little')")
  e("  return header + payload")
  e("")
  e("")
  e("def encode_message(message) -> bytes:")
  e("  message._validate()")
  e("  writer = _Writer()")
  e("  message._encode(writer)")
  e("  return _frame(MESSAGE_KINDS[_CLASS_NAMES[type(message)]], writer.out())")
  e("")
  e("")
  e("def encode_many(messages) -> bytes:")
  e('  return b"".join(encode_message(message) for message in messages)')
  e("")
  e("")
  e("def decode_stream(data: bytes) -> list:")
  e("  messages = []")
  e("  pos = 0")
  e("  total = len(data)")
  e("  while pos < total:")
  e("    if total - pos < FRAME_HEADER_BYTES + 1:")
  e('      raise ProtocolError("frame", "truncated frame header")')
  e("    if data[pos : pos + 2] != MAGIC:")
  e('      raise ProtocolError("frame.magic", "bad magic")')
  e("    version = data[pos + 2]")
  e("    if version != WIRE_VERSION:")
  e('      raise ProtocolError("frame.version", f"unknown wire version {version}")')
  e("    kind = data[pos + 3]")
  e("    length = int.from_bytes(data[pos + 4 : pos + 6], 'little')")
  e("    payload_start = pos + FRAME_HEADER_BYTES + 1")
  e("    payload_end = payload_start + length")
  e("    if payload_end > total:")
  e('      raise ProtocolError("frame.length", "truncated payload")')
  e("    if kind not in _KIND_CLASSES:")
  e('      raise ProtocolError("frame.kind", f"unknown message kind {kind}")')
  e("    name = _KIND_NAMES[kind]")
  e("    reader = _Reader(data, payload_start, payload_end)")
  e("    decoder: Any = _KIND_CLASSES[kind]")
  e("    message = decoder._decode(reader, name)")
  e("    if reader.pos != payload_end:")
  e('      raise ProtocolError("frame.length", f"{name} payload has trailing bytes")')
  e("    messages.append(message)")
  e("    pos = payload_end")
  e("  return messages")
  e("")
  e("")
  e("def reencode(data: bytes) -> bytes:")
  e('  """Decode every frame and encode it back; byte-identical for canonical input."""')
  e("  return encode_many(decode_stream(data))")
  e("")
  return "\n".join(L).rstrip() + "\n"


def _py_helpers(e) -> None:
  e("def _ck_eq(value: int, expect: int, field: str) -> None:")
  e("  if value != expect:")
  e('    raise ProtocolError(field, f"value {value!r} must equal {expect}")')
  e("")
  e("")
  e("def _ck_range(value: int, low: int, high: int, field: str) -> None:")
  e("  if not isinstance(value, int) or isinstance(value, bool) or not low <= value <= high:")
  e('    raise ProtocolError(field, f"value {value!r} outside [{low}, {high}]")')
  e("")
  e("")
  e("def _ck_enum(value: int, valid: frozenset[int], field: str) -> None:")
  e("  if not isinstance(value, int) or isinstance(value, bool) or value not in valid:")
  e('    raise ProtocolError(field, f"unknown enum value {value!r}")')
  e("")
  e("")
  e("def _ck_bool(value: bool, field: str) -> None:")
  e("  if not isinstance(value, bool):")
  e('    raise ProtocolError(field, "bool8 requires a Python bool")')
  e("")
  e("")
  e("def _ck_wire_bool(value: int, field: str) -> None:")
  e("  if value not in (0, 1):")
  e('    raise ProtocolError(field, f"non-canonical bool8 byte {value!r}")')
  e("")
  e("")
  e("def _fp32_key(bits: int) -> int:")
  e('  """Monotonic key of an FP32 word: unsigned key order == FP32 value order."""')
  e("  return (~bits & 0xFFFFFFFF) if bits & 0x80000000 else (bits | 0x80000000)")
  e("")
  e("")
  e("def _ck_items(values, low: int, high: int, field: str) -> None:")
  e("  for index, value in enumerate(values):")
  e('    _ck_range(value, low, high, f"{field}[{index}]")')
  e("")
  e("")
  e("def _ck_fp32_pos(bits: int, field: str) -> None:")
  e("  exponent = (bits >> 23) & 0xFF")
  e("  mantissa = bits & 0x7FFFFF")
  e("  if (bits >> 31) & 1 or exponent == 0xFF or (exponent == 0 and mantissa == 0):")
  e('    raise ProtocolError(field, f"FP32 word 0x{bits:08x} is not finite and strictly positive")')
  e("")
  e("")
  e("def _ck_fp32_not_nan(bits: int, field: str) -> None:")
  e("  if ((bits >> 23) & 0xFF) == 0xFF and bits & 0x7FFFFF:")
  e('    raise ProtocolError(field, f"FP32 word 0x{bits:08x} is NaN")')
  e("")
  e("")
  e("class _Writer:")
  e("  def __init__(self) -> None:")
  e("    self._buf = bytearray()")
  e("")
  e("  def u8(self, value: int) -> None:")
  e("    self._buf.append(value & 0xFF)")
  e("")
  e("  def i8(self, value: int) -> None:")
  e("    self._buf.append(value & 0xFF)")
  e("")
  e("  def u16(self, value: int) -> None:")
  e("    self._buf += value.to_bytes(2, 'little')")
  e("")
  e("  def i16(self, value: int) -> None:")
  e("    self._buf += value.to_bytes(2, 'little', signed=True)")
  e("")
  e("  def u32(self, value: int) -> None:")
  e("    self._buf += value.to_bytes(4, 'little')")
  e("")
  e("  def i32(self, value: int) -> None:")
  e("    self._buf += value.to_bytes(4, 'little', signed=True)")
  e("")
  e("  def u64(self, value: int) -> None:")
  e("    self._buf += value.to_bytes(8, 'little')")
  e("")
  e("  def out(self) -> bytes:")
  e("    return bytes(self._buf)")
  e("")
  e("")
  e("class _Reader:")
  e("  def __init__(self, data: bytes, pos: int, end: int) -> None:")
  e("    self._data = data")
  e("    self.pos = pos")
  e("    self._end = end")
  e("")
  e("  def _need(self, width: int, field: str) -> None:")
  e("    if self.pos + width > self._end:")
  e('      raise ProtocolError(field, "truncated payload")')
  e("")
  e("  def _read(self, width: int, field: str, signed: bool) -> int:")
  e("    self._need(width, field)")
  e("    chunk = self._data[self.pos : self.pos + width]")
  e("    self.pos += width")
  e("    return int.from_bytes(chunk, 'little', signed=signed)")
  e("")
  e("  def u8(self, field: str) -> int:")
  e("    return self._read(1, field, signed=False)")
  e("")
  e("  def i8(self, field: str) -> int:")
  e("    return self._read(1, field, signed=True)")
  e("")
  e("  def u16(self, field: str) -> int:")
  e("    return self._read(2, field, signed=False)")
  e("")
  e("  def i16(self, field: str) -> int:")
  e("    return self._read(2, field, signed=True)")
  e("")
  e("  def u32(self, field: str) -> int:")
  e("    return self._read(4, field, signed=False)")
  e("")
  e("  def i32(self, field: str) -> int:")
  e("    return self._read(4, field, signed=True)")
  e("")
  e("  def u64(self, field: str) -> int:")
  e("    return self._read(8, field, signed=False)")
  e("")
  e("")


def _py_struct(e, model: dict, struct: Struct) -> None:
  cls = pascal(struct.name)
  e("@dataclass(frozen=True)")
  e(f"class {cls}:")
  if struct.note:
    first_sentence = struct.note.split(". ")[0] + ("." if not struct.note.endswith(".") else "")
    e(f'  """{first_sentence}"""')
  for field in struct.fields:
    e(f"  {field.name}: {_py_field_type(field)}")
  e("")
  e(f"  def _validate(self, _p: str = {cls!r}) -> None:")
  for field in struct.fields:
    _py_field_validate(e, field, "    ")
  for predicate in struct.predicates:
    _py_predicate(e, predicate, "    ")
  e("")
  e("  def _encode(self, _o: _Writer) -> None:")
  for field in struct.fields:
    _py_field_encode(e, field, "    ")
  e("")
  e("  @classmethod")
  e(f"  def _decode(cls, _r: _Reader, _p: str) -> {cls}:")
  args = []
  for field in struct.fields:
    _py_field_decode(e, field, "    ")
    args.append(field.name)
  joined = ", ".join(f"{name}={name}" for name in args)
  if len(joined) > 96:
    e("    value = cls(")
    for name in args:
      e(f"      {name}={name},")
    e("    )")
  else:
    e(f"    value = cls({joined})")
  e("    value._validate(_p)")
  e("    return value")
  e("")
  e("")


def _py_field_validate(e, field: Field, indent: str) -> None:
  target = f"self.{field.name}"
  p = f"{{_p}}.{field.name}"
  if field.kind == "scalar":
    if field.type == "bool8":
      e(f"{indent}_ck_bool({target}, f'{p}')")
    else:
      low, high = scalar_bounds(field)
      e(f"{indent}_ck_range({target}, {low}, {high}, f'{p}')")
  elif field.kind == "enum":
    e(f"{indent}_ck_enum({target}, _{field.ref_name.upper()}_VALID, f'{p}')")
  elif field.kind == "struct":
    e(f"{indent}{target}._validate(f'{p}')")
  elif field.kind == "list":
    if field.item_range:
      e(f"{indent}_ck_items({target}, {field.item_range[0]}, {field.item_range[1]}, f'{p}')")
    elif field.elem_kind == "enum":
      enum_name = field.elem_ref
      e(f"{indent}for _item_{field.name} in {target}:")
      e(f"{indent}  _ck_enum(_item_{field.name}, _{enum_name.upper()}_VALID, f'{p}')")
    elif field.elem_kind == "struct":
      e(f"{indent}for _item_{field.name} in {target}:")
      e(f"{indent}  _item_{field.name}._validate(f'{p}')")
    if field.count_field:
      limit = 255 if field.count_field == "u8" else 65535
      e(f"{indent}_ck_range(len({target}), 0, {limit}, f'{p}.count')")
  if field.predicate == "dtype_width":
    e(f"{indent}_ck_eq({target}, DTYPE_ELEMENT_BYTES[self.dtype], f'{p}')")
  elif field.predicate == "fp32_pos":
    e(f"{indent}_ck_fp32_pos({target}, f'{p}')")
  elif field.predicate == "fp32_not_nan":
    e(f"{indent}_ck_fp32_not_nan({target}, f'{p}')")


def _py_field_encode(e, field: Field, indent: str) -> None:
  target = f"self.{field.name}"
  if field.kind == "scalar":
    if field.type == "bool8":
      e(f"{indent}_o.u8(1 if {target} else 0)")
    else:
      e(f"{indent}_o.{field.type}({target})")
  elif field.kind == "enum":
    e(f"{indent}_o.u8({target})")
  elif field.kind == "struct":
    e(f"{indent}{target}._encode(_o)")
  elif field.kind == "list":
    count = field.count_field or "u16"
    e(f"{indent}_o.{count}(len({target}))")
    if field.elem_kind == "struct":
      e(f"{indent}for _item_{field.name} in {target}:")
      e(f"{indent}  _item_{field.name}._encode(_o)")
    elif field.elem_kind == "enum":
      e(f"{indent}for _item_{field.name} in {target}:")
      e(f"{indent}  _o.u8(_item_{field.name})")
    else:
      e(f"{indent}for _item_{field.name} in {target}:")
      e(f"{indent}  _o.{field.elem_type}(_item_{field.name})")


def _py_field_decode(e, field: Field, indent: str) -> None:
  p = f"{{_p}}.{field.name}"
  if field.kind == "scalar":
    method = "u8" if field.type == "bool8" else field.type
    e(f"{indent}{field.name} = _r.{method}(f'{p}')")
    if field.type == "bool8":
      e(f"{indent}_ck_wire_bool({field.name}, f'{p}')")
      e(f"{indent}{field.name} = bool({field.name})")
  elif field.kind == "enum":
    e(f"{indent}{field.name} = _r.u8(f'{p}')")
  elif field.kind == "struct":
    e(f"{indent}{field.name} = {field.ref_name}._decode(_r, f'{p}')")
  elif field.kind == "list":
    if field.count_field:
      e(f"{indent}_count = _r.{field.count_field}(f'{p}.count')")
    else:
      e(f"{indent}_count = {field.count_expr}")
    if field.elem_kind == "struct":
      e(f"{indent}{field.name} = tuple(")
      e(f"{indent}    {field.elem_ref}._decode(_r, f'{p}[_i]')")
      e(f"{indent}    for _i in range(_count)")
      e(f"{indent})")
    elif field.elem_kind == "enum":
      e(f"{indent}{field.name} = tuple(_r.u8(f'{p}[_i]') for _i in range(_count))")
    else:
      e(f"{indent}{field.name} = tuple(_r.{field.elem_type}(f'{p}[_i]') for _i in range(_count))")


def _py_predicate(e, predicate: dict, indent: str) -> None:
  kind = predicate["kind"]
  if kind == "eq_product":
    constant = predicate.get("constant", 1)
    product = " * ".join(f"self.{name}" for name in predicate["factors"])
    if constant != 1:
      product += f" * {constant}"
    expect = " * ".join(predicate["factors"]) + ("" if constant == 1 else f" * {constant}")
    e(f"{indent}if self.{predicate['target']} != {product}:")
    e(f"{indent}  raise ProtocolError(f'{{_p}}.{predicate['target']}', 'must equal {expect}')")
  elif kind == "fp32_le":
    e(f"{indent}if _fp32_key(self.{predicate['left']}) > _fp32_key(self.{predicate['right']}):")
    e(
      f"{indent}  raise ProtocolError(f'{{_p}}.{predicate['left']}',"
      f" 'must be <= {predicate['right']} as FP32 values')"
    )
  elif kind == "eq_field":
    left = ".".join(["self", *predicate["left"].split(".")])
    right = ".".join(["self", *predicate["right"].split(".")])
    e(f"{indent}if {left} != {right}:")
    e(f"{indent}  raise ProtocolError(f'{{_p}}.{predicate['left']}', 'must equal {predicate['right']}')")
  elif kind == "not_contains_token":
    token = ".".join(["self", *predicate["token_field"].split(".")])
    e(f"{indent}if any(")
    e(f"{indent}  _item.ctx_id == {token}.ctx_id")
    e(f"{indent}  and _item.ctx_epoch == {token}.ctx_epoch")
    e(f"{indent}  and _item.event_id == {token}.event_id")
    e(f"{indent}  for _item in self.{predicate['list_field']}")
    e(f"{indent}):")
    e(
      f"{indent}  raise ProtocolError("
      f"f'{{_p}}.{predicate['list_field']}',"
      " 'a step must not wait on its own completion event')"
    )
  elif kind == "quant_i8":
    dtype_field = predicate["dtype_field"]
    quant = ".".join(["self", *predicate["quant_field"].split(".")])
    e(f"{indent}_is_i8 = self.{dtype_field} == DTYPE_I8")
    e(f"{indent}_has_quant = {quant} is not None")
    e(f"{indent}if _is_i8 != _has_quant:")
    e(
      f"{indent}  raise ProtocolError(f'{{_p}}.{dtype_field}',"
      f" 'i8 output requires exactly the quant parameters')"
    )
  else:
    raise SchemaError(f"unsupported predicate kind {kind}")


def _py_epilogue(e) -> None:
  e("@dataclass(frozen=True)")
  e("class EpilogueConfig:")
  e('  """FINAL-only post-processing block; presence bits derive from the values."""')
  e("")
  e("  n_cols: int")
  e("  bias: tuple[int, ...] | None = None")
  e("  scale: int | None = None")
  e("  relu: bool = False")
  e("  clip: ClipPair | None = None")
  e("  quant: QuantConfig | None = None")
  e("")
  e("  def enables(self) -> int:")
  e("    return (")
  e("      (EPILOGUE_EN_BIAS if self.bias is not None else 0)")
  e("      | (EPILOGUE_EN_SCALE if self.scale is not None else 0)")
  e("      | (EPILOGUE_EN_RELU if self.relu else 0)")
  e("      | (EPILOGUE_EN_CLIP if self.clip is not None else 0)")
  e("      | (EPILOGUE_EN_QUANT if self.quant is not None else 0)")
  e("    )")
  e("")
  e("  def _validate(self, _p: str = 'EpilogueConfig') -> None:")
  e("    _ck_range(self.n_cols, 0, 65535, f'{_p}.n_cols')")
  e("    if self.bias is not None and len(self.bias) != self.n_cols:")
  e("      raise ProtocolError(f'{_p}.bias', 'bias word count must equal n_cols')")
  e("    if self.scale is not None:")
  e("      _ck_range(self.scale, 0, 0xFFFFFFFF, f'{_p}.scale')")
  e("    _ck_bool(self.relu, f'{_p}.relu')")
  e("    if self.clip is not None:")
  e("      self.clip._validate(f'{_p}.clip')")
  e("    if self.quant is not None:")
  e("      self.quant._validate(f'{_p}.quant')")
  e("")
  e("  def _encode(self, _o: _Writer) -> None:")
  e("    _o.u16(self.n_cols)")
  e("    _o.u8(self.enables())")
  e("    bias = self.bias or ()")
  e("    for _i in range(self.n_cols):")
  e("      _o.u32(bias[_i] if _i < len(bias) else 0)")
  e("    _o.u32(self.scale if self.scale is not None else 0)")
  e("    clip = self.clip if self.clip is not None else ClipPair(0, 0)")
  e("    clip._encode(_o)")
  e("    quant = self.quant if self.quant is not None else QuantConfig(0, 0)")
  e("    quant._encode(_o)")
  e("")
  e("  @classmethod")
  e("  def _decode(cls, _r: _Reader, _p: str) -> EpilogueConfig:")
  e("    n_cols = _r.u16(f'{_p}.n_cols')")
  e("    enables = _r.u8(f'{_p}.enables')")
  e("    if enables & EPILOGUE_RESERVED_MASK:")
  e("      raise ProtocolError(f'{_p}.enables', 'reserved bits must be zero')")
  e("    bias: tuple[int, ...] | None = tuple(")
  e("      _r.u32(f'{_p}.bias[_i]') for _i in range(n_cols)")
  e("    )")
  e("    if not enables & EPILOGUE_EN_BIAS:")
  e("      if any(bias or ()):")
  e("        raise ProtocolError(f'{_p}.bias', 'disabled stage must serialize zeros')")
  e("      bias = None")
  e("    scale: int | None = _r.u32(f'{_p}.scale')")
  e("    if not enables & EPILOGUE_EN_SCALE:")
  e("      if scale:")
  e("        raise ProtocolError(f'{_p}.scale', 'disabled stage must serialize zeros')")
  e("      scale = None")
  e("    _clip_lo = _r.u32(f'{_p}.clip.lo')")
  e("    _clip_hi = _r.u32(f'{_p}.clip.hi')")
  e("    clip: ClipPair | None = None")
  e("    if enables & EPILOGUE_EN_CLIP:")
  e("      clip = ClipPair(lo=_clip_lo, hi=_clip_hi)")
  e("      clip._validate(f'{_p}.clip')")
  e("    elif _clip_lo or _clip_hi:")
  e("      raise ProtocolError(f'{_p}.clip', 'disabled stage must serialize zeros')")
  e("    _inv_scale = _r.u32(f'{_p}.quant.inv_scale')")
  e("    _zero_point = _r.i8(f'{_p}.quant.zero_point')")
  e("    quant: QuantConfig | None = None")
  e("    if enables & EPILOGUE_EN_QUANT:")
  e("      quant = QuantConfig(inv_scale=_inv_scale, zero_point=_zero_point)")
  e("      quant._validate(f'{_p}.quant')")
  e("    elif _inv_scale or _zero_point:")
  e("      raise ProtocolError(f'{_p}.quant', 'disabled stage must serialize zeros')")
  e("    value = cls(")
  e("      n_cols=n_cols,")
  e("      bias=bias,")
  e("      scale=scale,")
  e("      relu=bool(enables & EPILOGUE_EN_RELU),")
  e("      clip=clip,")
  e("      quant=quant,")
  e("    )")
  e("    value._validate(_p)")
  e("    return value")
  e("")
  e("")


def _py_evt_take(e, model: dict) -> None:
  union = model["messages"]["EVT_TAKE"].raw["union"]
  tag_enum = union["tag_type"].split(":", 1)[1]
  variants = " | ".join(pascal(v) for v in union["variants"])
  e("@dataclass(frozen=True)")
  e("class EvtTake:")
  e('  """Destructive take of one wake record or one event slot terminal."""')
  e(f"  record: {variants}")
  e("")
  e("  def _validate(self, _p: str = 'EvtTake') -> None:")
  e("    self.record._validate(f'{_p}.record')")
  e("")
  e("  def _encode(self, _o: _Writer) -> None:")
  for vname, _ in enum_values(model, tag_enum):
    e(f"    if isinstance(self.record, {pascal(vname)}):")
    e(f"      _o.u8({enum_const(tag_enum, vname)})")
  e("    self.record._encode(_o)")
  e("")
  e("  @classmethod")
  e("  def _decode(cls, _r: _Reader, _p: str) -> EvtTake:")
  e("    _tag = _r.u8(f'{_p}.record')")
  e(f"    _ck_enum(_tag, _{tag_enum.upper()}_VALID, f'{{_p}}.record')")
  for index, (vname, value) in enumerate(enum_values(model, tag_enum)):
    keyword = "if" if index == 0 else "elif"
    e(f"    {keyword} _tag == {value}:")
    e(f"      _record_{vname} = {pascal(vname)}._decode(_r, f'{{_p}}.record')")
  e("    else:")
  e("      raise ProtocolError(f'{_p}.record', 'unreachable tag')")
  e("    _record: Wake | StepTerminal | ChainTerminal = (")
  e("      _record_wake")
  e("      if _tag == 0")
  e("      else _record_step_terminal")
  e("      if _tag == 1")
  e("      else _record_chain_terminal")
  e("    )")
  e("    value = cls(record=_record)")
  e("    value._validate(_p)")
  e("    return value")
  e("")
  e("")



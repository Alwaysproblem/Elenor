C_SCALARS = {
  "u8": "uint8_t",
  "u16": "uint16_t",
  "u32": "uint32_t",
  "u64": "uint64_t",
  "i8": "int8_t",
  "i16": "int16_t",
  "i32": "int32_t",
  "bool8": "uint8_t",
}


def _c_list_type(field: Field) -> str:
  elem = field.elem_type
  if elem in C_SCALARS:
    return f"boa_{elem}_list"
  return f"boa_{c_sym(field.elem_ref)}_list"


def _c_field_type(field: Field) -> str:
  if field.kind == "scalar":
    return C_SCALARS[field.type]
  if field.kind == "enum":
    return "uint8_t"
  if field.kind == "struct":
    return f"boa_{c_sym(field.ref_name)}"
  return _c_list_type(field)


def emit_c(schema: dict, model: dict) -> str:
  L: list[str] = []
  e = L.append
  e("/*")
  e(f" * {GENERATOR_NOTE}")
  e(" *")
  e(" * Decode-side validation is strict (ranges, enums, canonical bools,")
  e(" * reserved enable bits, cross-field predicates); every rejection names")
  e(" * the offending field.  Encode assumes values that already passed")
  e(" * validation (re-encoding decoded frames is always canonical).")
  e(" *")
  e(" * Define BOA_PROTOCOL_IMPLEMENTATION in exactly one translation unit.")
  e(" */")
  e("#ifndef BOA_PROTOCOL_H")
  e("#define BOA_PROTOCOL_H")
  e("")
  e("#include <stddef.h>")
  e("#include <stdint.h>")
  e("")
  e(f"#define BOA_WIRE_VERSION {schema['abi']['wire_version_int']}")
  e("#define BOA_MAGIC0 0x42")
  e("#define BOA_MAGIC1 0x50")
  e("#define BOA_FRAME_HEADER_BYTES 5")
  caps = schema["capacities"]
  for name in ("am_group_count", "am_slots_per_group", "am_slots_per_context", "am_total_slots_per_tile"):
    e(f"#define BOA_{name.upper()} {caps[name]['value']}")
  e(f"#define BOA_AM_SLOT_CAPACITY_BYTES_MAX {caps['am_slot_capacity_bytes']['legal_range'][1]}")
  e("#define BOA_EPILOGUE_EN_BIAS 0x01")
  e("#define BOA_EPILOGUE_EN_SCALE 0x02")
  e("#define BOA_EPILOGUE_EN_RELU 0x04")
  e("#define BOA_EPILOGUE_EN_CLIP 0x08")
  e("#define BOA_EPILOGUE_EN_QUANT 0x10")
  e("#define BOA_EPILOGUE_RESERVED_MASK 0xE0")
  for ename in sorted(model["enums"]):
    for vname, value in enum_values(model, ename):
      e(f"#define BOA_{ename.upper()}_{vname.upper()} {value}")
  e("")
  e("#if defined(__GNUC__)")
  e("#define BOA_UNUSED __attribute__((unused))")
  e("#else")
  e("#define BOA_UNUSED")
  e("#endif")
  e("")
  e("typedef struct {")
  e("  const char *field;")
  e("  const char *reason;")
  e("} boa_err;")
  e("")
  e("#ifdef BOA_PROTOCOL_IMPLEMENTATION")
  e("#include <stdlib.h>")
  e("#include <string.h>")
  e("#endif")
  e("")
  e("typedef struct { size_t count; uint8_t *items; } boa_u8_list;")
  e("typedef struct { size_t count; uint16_t *items; } boa_u16_list;")
  e("typedef struct { size_t count; uint32_t *items; } boa_u32_list;")
  e("")
  list_elements = {
    field.elem_ref
    for struct in list(model["structs"].values()) + list(model["messages"].values())
    for field in struct.fields
    if field.kind == "list" and field.elem_kind == "struct"
  }
  for struct in regular_structs(model):
    _c_struct_decl(e, struct)
    if struct.name in list_elements:
      e(
        f"typedef struct {{ size_t count; boa_{c_sym(struct.name)} *items; }}"
        f" boa_{c_sym(struct.name)}_list;"
      )
      e("")
  _c_epilogue_decl(e)
  for variant in [model["variants"][name] for name in sorted(model["variants"])]:
    _c_struct_decl(e, variant)
  e("typedef struct {")
  e("  uint8_t record_kind;")
  e("  union {")
  union = model["messages"]["EVT_TAKE"].raw["union"]
  for vname in union["variants"]:
    e(f"    boa_{vname.lower()} {vname.lower()};")
  e("  } rec;")
  e("} boa_evt_take;")
  e("")
  for message in regular_messages(model):
    _c_struct_decl(e, message)
  e("typedef struct {")
  e("  uint8_t kind;")
  e("  union {")
  for name in message_names_by_kind(model):
    e(f"    boa_{name.lower()} {name.lower()};")
  e("  } as;")
  e("} boa_msg;")
  e("")
  e("const char *boa_kind_name(uint8_t kind);")
  e("void boa_msg_free(boa_msg *message);")
  e("/* Both return the consumed/written byte count (>= 6), or -1 with err set. */")
  e("long boa_decode_frame(const uint8_t *buf, size_t len, boa_msg *out, boa_err *err);")
  e("long boa_encode_frame(const boa_msg *message, uint8_t *buf, size_t cap, boa_err *err);")
  e("")
  e("#ifdef BOA_PROTOCOL_IMPLEMENTATION")
  e("")
  e("const char *boa_kind_name(uint8_t kind) {")
  e("  switch (kind) {")
  for name in message_names_by_kind(model):
    e(f'    case {model["messages"][name].kind_id}: return "{name}";')
  e('    default: return "UNKNOWN";')
  e("  }")
  e("}")
  e("")
  e("BOA_UNUSED static int boa_fail(boa_err *err, const char *field, const char *reason) {")
  e("  if (err != NULL) {")
  e("    err->field = field;")
  e("    err->reason = reason;")
  e("  }")
  e("  return -1;")
  e("}")
  e("")
  e("BOA_UNUSED static int boa_need(const uint8_t *buf, size_t pos, size_t end, size_t width,")
  e("                    const char *field, boa_err *err) {")
  e("  (void)buf;")
  e("  if (pos + width > end)")
  e('    return boa_fail(err, field, "truncated payload");')
  e("  return 0;")
  e("}")
  e("")
  for scalar in ("u8", "i8", "u16", "i16", "u32", "i32", "u64"):
    e(_c_reader_fn(scalar))
    e("")
  e("BOA_UNUSED static uint32_t boa_fp32_key(uint32_t bits) {")
  e("  return (bits & 0x80000000u) ? (~bits & 0xffffffffu) : (bits | 0x80000000u);")
  e("}")
  e("")
  e("BOA_UNUSED static uint8_t *boa_wr(uint8_t *cur, const uint8_t *end, uint64_t value, size_t width) {")
  e("  size_t index;")
  e("  if ((size_t)(end - cur) < width)")
  e("    return NULL;")
  e("  for (index = 0; index < width; index++) {")
  e("    cur[index] = (uint8_t)(value & 0xff);")
  e("    value >>= 8;")
  e("  }")
  e("  return cur + width;")
  e("}")
  e("")
  for struct in regular_structs(model):
    _c_code(e, model, struct)
  _c_epilogue_code(e)
  for variant in [model["variants"][name] for name in sorted(model["variants"])]:
    _c_code(e, model, variant)
  _c_evt_take_code(e, model)
  for message in regular_messages(model):
    _c_code(e, model, message)
  e("BOA_UNUSED static long boa_encode_payload(const boa_msg *message, uint8_t *buf, size_t cap,")
  e("                              boa_err *err) {")
  e("  uint8_t *cur = buf;")
  e("  const uint8_t *end = buf + cap;")
  e("  switch (message->kind) {")
  for name in message_names_by_kind(model):
    e(f"    case {model['messages'][name].kind_id}:")
    e(f"      if (boa_enc_{name.lower()}(&message->as.{name.lower()}, &cur, end, err) != 0)")
    e("        return -1;")
    e("      break;")
  e("    default:")
  e('      return boa_fail(err, "frame.kind", "unknown message kind");')
  e("  }")
  e("  return (long)(cur - buf);")
  e("}")
  e("")
  e("long boa_encode_frame(const boa_msg *message, uint8_t *buf, size_t cap, boa_err *err) {")
  e("  uint8_t *cur;")
  e("  const uint8_t *end = buf + cap;")
  e("  long payload;")
  e("  if (cap < 6)")
  e('    return boa_fail(err, "frame.length", "buffer too small");')
  e("  payload = boa_encode_payload(message, buf + 6, cap - 6, err);")
  e("  if (payload < 0)")
  e("    return -1;")
  e("  cur = boa_wr(buf, end, BOA_MAGIC0, 1);")
  e("  cur = boa_wr(cur, end, BOA_MAGIC1, 1);")
  e("  cur = boa_wr(cur, end, BOA_WIRE_VERSION, 1);")
  e("  cur = boa_wr(cur, end, message->kind, 1);")
  e("  cur = boa_wr(cur, end, (uint64_t)payload, 2);")
  e("  if (cur == NULL)")
  e('    return boa_fail(err, "frame.length", "buffer too small");')
  e("  return 6 + payload;")
  e("}")
  e("")
  e("static long boa_decode_payload(uint8_t kind, const uint8_t *buf, size_t len, boa_msg *out,")
  e("                              boa_err *err) {")
  e("  size_t pos = 0;")
  e("  switch (kind) {")
  for name in message_names_by_kind(model):
    e(f"    case {model['messages'][name].kind_id}:")
    e(f"      return boa_dec_{name.lower()}(buf, &pos, len, &out->as.{name.lower()}, err);")
  e("    default:")
  e('      return boa_fail(err, "frame.kind", "unknown message kind");')
  e("  }")
  e("}")
  e("")
  e("long boa_decode_frame(const uint8_t *buf, size_t len, boa_msg *out, boa_err *err) {")
  e("  size_t payload_len;")
  e("  long used;")
  e("  if (len < 6)")
  e('    return boa_fail(err, "frame", "truncated frame header");')
  e("  if (buf[0] != BOA_MAGIC0 || buf[1] != BOA_MAGIC1)")
  e('    return boa_fail(err, "frame.magic", "bad magic");')
  e("  if (buf[2] != BOA_WIRE_VERSION)")
  e('    return boa_fail(err, "frame.version", "unknown wire version");')
  e("  payload_len = (size_t)buf[4] | ((size_t)buf[5] << 8);")
  e("  if (6 + payload_len > len)")
  e('    return boa_fail(err, "frame.length", "truncated payload");')
  e("  memset(out, 0, sizeof(*out));")
  e("  out->kind = buf[3];")
  e("  used = boa_decode_payload(buf[3], buf + 6, payload_len, out, err);")
  e("  if (used < 0)")
  e("    return -1;")
  e("  if ((size_t)used != payload_len)")
  e('    return boa_fail(err, "frame.length", "payload has trailing bytes");')
  e("  return (long)(6 + payload_len);")
  e("}")
  e("")
  e("void boa_msg_free(boa_msg *message) {")
  e("  switch (message->kind) {")
  for name in message_names_by_kind(model):
    e(f"    case {model['messages'][name].kind_id}:")
    e(f"      boa_free_{name.lower()}(&message->as.{name.lower()});")
    e("      break;")
  e("    default:")
  e("      break;")
  e("  }")
  e("  memset(message, 0, sizeof(*message));")
  e("}")
  e("")
  e("#endif /* BOA_PROTOCOL_IMPLEMENTATION */")
  e("#endif /* BOA_PROTOCOL_H */")
  return "\n".join(L).rstrip() + "\n"


def _c_reader_fn(scalar: str) -> str:
  ctype = C_SCALARS[scalar]
  width, signed = SCALARS[scalar]
  lines = [
    f"BOA_UNUSED static int rd_{scalar}(const uint8_t *buf, size_t *pos, size_t end, {ctype} *out,",
    "                       const char *field, boa_err *err) {",
    f"  if (boa_need(buf, *pos, end, {width}, field, err) != 0)",
    "    return -1;",
  ]
  if width == 1:
    lines.append(f"  *out = ({ctype})buf[*pos];")
  else:
    holder = (
      ctype
      if not signed
      else ctype.replace("int8", "uint8").replace("int16", "uint16").replace("int32", "uint32")
    )
    lines += [
      f"  {holder} value = 0;",
      "  size_t index;",
      f"  for (index = 0; index < {width}; index++)",
      f"    value |= ({holder})buf[*pos + index] << (8 * index);",
      f"  *out = ({ctype})value;",
    ]
  lines += [f"  *pos += {width};", "  return 0;", "}"]
  return "\n".join(lines)


def _c_struct_decl(e, struct: Struct) -> None:
  e(f"/* {struct.name} */")
  e("typedef struct {")
  for field in struct.fields:
    e(f"  {_c_field_type(field)} {field.name};")
  e(f"}} boa_{c_sym(struct.name)};")
  e("")


def _c_epilogue_decl(e) -> None:
  e("/* EpilogueConfig: fixed layout; enables presence bits are derived. */")
  e("typedef struct {")
  e("  uint16_t n_cols;")
  e("  uint8_t enables;")
  e("  uint8_t relu;")
  e("  uint8_t scale_present;")
  e("  uint8_t clip_present;")
  e("  uint8_t quant_present;")
  e("  boa_u32_list bias; /* count == n_cols; items NULL when disabled */")
  e("  uint32_t scale; /* 0 when disabled */")
  e("  boa_clip_pair clip; /* zeros when disabled */")
  e("  boa_quant_config quant; /* zeros when disabled */")
  e("} boa_epilogue_config;")
  e("")


def _c_code(e, model: dict, struct: Struct) -> None:
  name = c_sym(struct.name)
  e(
    f"BOA_UNUSED static int boa_enc_{name}(const boa_{name} *m, uint8_t **cur, const uint8_t *end,"
    f" boa_err *err) {{"
  )
  e("  uint8_t *c = *cur;")
  e("  (void)err;")
  for field in struct.fields:
    _c_enc_field(e, field, "  ")
  e("  if (c == NULL)")
  e(f'    return boa_fail(err, "{struct.name}", "buffer too small");')
  e("  *cur = c;")
  e("  return 0;")
  e("}")
  e("")
  e(
    f"BOA_UNUSED static long boa_dec_{name}(const uint8_t *buf, size_t *pos, size_t end,"
    f" boa_{name} *m, boa_err *err) {{"
  )
  for field in struct.fields:
    _c_dec_field(e, model, struct, field, "  ")
  _c_predicates(e, struct)
  e("  return (long)(*pos);")
  e("}")
  e("")
  e(f"BOA_UNUSED static void boa_free_{name}(boa_{name} *m) {{")
  freed = False
  for field in struct.fields:
    if field.kind == "list":
      e(f"  free(m->{field.name}.items);")
      e(f"  m->{field.name}.items = NULL;")
      e(f"  m->{field.name}.count = 0;")
      freed = True
    elif field.kind == "struct":
      e(f"  boa_free_{c_sym(field.ref_name)}(&m->{field.name});")
      freed = True
  if not freed:
    e("  (void)m;")
  e("}")
  e("")


def _c_enc_field(e, field: Field, indent: str) -> None:
  member = f"m->{field.name}"
  if field.kind == "scalar":
    width = SCALARS[field.type][0]
    cast = "(uint64_t)"
    if field.type == "bool8":
      e(f"{indent}c = boa_wr(c, end, {member} ? 1 : 0, 1);")
      return
    e(f"{indent}c = boa_wr(c, end, {cast}{member}, {width});")
  elif field.kind == "enum":
    e(f"{indent}c = boa_wr(c, end, (uint64_t){member}, 1);")
  elif field.kind == "struct":
    e(f"{indent}if (boa_enc_{c_sym(field.ref_name)}(&{member}, &c, end, err) != 0)")
    e(f"{indent}  return -1;")
  elif field.kind == "list":
    count = field.count_field or "u16"
    width = 1 if count == "u8" else 2
    e(f"{indent}c = boa_wr(c, end, (uint64_t){member}.count, {width});")
    elem = field.elem_type
    if elem in C_SCALARS:
      item_width = SCALARS[elem][0]
      e(f"{indent}size_t {field.name}_index;")
      e(f"{indent}for ({field.name}_index = 0; {field.name}_index < {member}.count; {field.name}_index++)")
      e(f"{indent}  c = boa_wr(c, end, (uint64_t){member}.items[{field.name}_index], {item_width});")
    else:
      e(f"{indent}size_t {field.name}_index;")
      e(f"{indent}for ({field.name}_index = 0; {field.name}_index < {member}.count; {field.name}_index++)")
      e(
        f"{indent}  if (boa_enc_{c_sym(field.elem_ref)}(&{member}.items[{field.name}_index],"
        f" &c, end, err) != 0)"
      )
      e(f"{indent}    return -1;")


def _c_dec_field(e, model: dict, struct: Struct, field: Field, indent: str) -> None:
  member = f"m->{field.name}"
  fld = f"{struct.name}.{field.name}"
  if field.kind == "scalar":
    scalar = "u8" if field.type == "bool8" else field.type
    e(f'{indent}if (rd_{scalar}(buf, pos, end, &{member}, "{fld}", err) != 0)')
    e(f"{indent}  return -1;")
    if field.type == "bool8":
      e(f"{indent}if ({member} > 1)")
      e(f'  {indent}return boa_fail(err, "{fld}", "non-canonical bool8 byte");')
    else:
      low, high = scalar_bounds(field)
      natural_low, natural_high = SCALAR_BOUNDS[field.type]
      checks = []
      if low != natural_low:
        checks.append(f"{member} < {low}")
      if high != natural_high:
        checks.append(f"{member} > {high}")
      if checks:
        e(f"{indent}if ({' || '.join(checks)})")
        e(f'  {indent}return boa_fail(err, "{fld}", "value outside range");')
  elif field.kind == "enum":
    e(f'{indent}if (rd_u8(buf, pos, end, &{member}, "{fld}", err) != 0)')
    e(f"{indent}  return -1;")
    valid = " && ".join(f"{member} != {value}" for _, value in enum_values(model, field.ref_name))
    e(f"{indent}if ({valid})")
    e(f'  {indent}return boa_fail(err, "{fld}", "unknown enum value");')
  elif field.kind == "struct":
    e(f"{indent}if (boa_dec_{c_sym(field.ref_name)}(buf, pos, end, &{member}, err) < 0)")
    e(f"{indent}  return -1;")
  elif field.kind == "list":
    bound = f"{field.name}_count"
    if field.count_field:
      raw = f"{field.name}_count_raw"
      e(f"{indent}{C_SCALARS[field.count_field]} {raw};")
      e(f'{indent}if (rd_{field.count_field}(buf, pos, end, &{raw}, "{fld}.count", err) != 0)')
      e(f"{indent}  return -1;")
      e(f"{indent}size_t {bound} = (size_t){raw};")
    else:
      e(f"{indent}size_t {bound} = (size_t)m->{field.count_expr};")
    e(f"{indent}{member}.count = {bound};")
    e(f"{indent}{member}.items = NULL;")
    e(f"{indent}if ({bound} > 0) {{")
    e(f"{indent}  {member}.items = calloc({bound}, sizeof(*{member}.items));")
    e(f"{indent}  if ({member}.items == NULL)")
    e(f'    {indent}return boa_fail(err, "{fld}", "out of memory");')
    e(f"{indent}}}")
    e(f"{indent}{{")
    e(f"{indent}  size_t {field.name}_index;")
    e(f"{indent}  for ({field.name}_index = 0; {field.name}_index < {bound}; {field.name}_index++) {{")
    elem = field.elem_type
    if elem in C_SCALARS:
      e(
        f"{indent}    if (rd_{elem}(buf, pos, end, &{member}.items[{field.name}_index],"
        f' "{fld}[]", err) != 0)'
      )
      e(f"{indent}      return -1;")
      if field.item_range:
        checks = []
        if field.item_range[0] != SCALAR_BOUNDS[elem][0]:
          checks.append(f"{member}.items[{field.name}_index] < {field.item_range[0]}")
        if field.item_range[1] != SCALAR_BOUNDS[elem][1]:
          checks.append(f"{member}.items[{field.name}_index] > {field.item_range[1]}")
        if checks:
          e(f"{indent}    if ({' || '.join(checks)})")
          e(f'      {indent}return boa_fail(err, "{fld}[]", "item outside range");')
    else:
      e(
        f"{indent}    if (boa_dec_{c_sym(field.elem_ref)}(buf, pos, end,"
        f" &{member}.items[{field.name}_index], err) < 0)"
      )
      e(f"{indent}      return -1;")
    e(f"{indent}  }}")
    e(f"{indent}}}")


def _c_predicates(e, struct: Struct) -> None:
  for predicate in struct.predicates:
    kind = predicate["kind"]
    if kind == "eq_product":
      constant = predicate.get("constant", 1)
      product = " * ".join(f"(uint64_t)m->{name}" for name in predicate["factors"])
      if constant != 1:
        product += " * (uint64_t)" + str(constant)
      target = predicate["target"]
      e(f"  if ((uint64_t)m->{target} != {product})")
      e(f'    return boa_fail(err, "{struct.name}.{target}", "must equal element product");')
    elif kind == "fp32_le":
      left = predicate["left"]
      right = predicate["right"]
      e(f"  if (boa_fp32_key(m->{left}) > boa_fp32_key(m->{right}))")
      e(f'    return boa_fail(err, "{struct.name}.{left}", "must be <= upper bound as FP32 values");')
    elif kind == "eq_field":
      left = _c_path(predicate["left"])
      right = _c_path(predicate["right"])
      e(f"  if ({left} != {right})")
      e(f'    return boa_fail(err, "{struct.name}.{predicate["left"]}", "fields must agree");')
    elif kind == "not_contains_token":
      token = _c_path(predicate["token_field"])
      the_list = predicate["list_field"]
      e("  {")
      e("    size_t self_ready_index;")
      e("    int self_ready = 0;")
      e(f"    for (self_ready_index = 0; self_ready_index < m->{the_list}.count;")
      e("         self_ready_index++) {")
      e(
        f"      if (m->{the_list}.items[self_ready_index].ctx_id == {token}.ctx_id &&"
      )
      e(
        f"          m->{the_list}.items[self_ready_index].ctx_epoch == {token}.ctx_epoch &&"
      )
      e("          m->" + the_list + ".items[self_ready_index].event_id ==")
      e(f"            {token}.event_id) {{")
      e("        self_ready = 1;")
      e("        break;")
      e("      }")
      e("    }")
      e("    if (self_ready)")
      e(
        f'      return boa_fail(err, "{struct.name}.{the_list}",'
        ' "a step must not wait on its own completion event");'
      )
      e("  }")
    elif kind == "quant_i8":
      dtype_field = predicate["dtype_field"]
      parent, _, leaf = predicate["quant_field"].rpartition(".")
      present = f"m->{parent}.{leaf}_present" if parent else f"m->{leaf}_present"
      e(f"  int is_i8 = (m->{dtype_field} == BOA_DTYPE_I8);")
      e(f"  int has_quant = ({present} != 0);")
      e("  if (is_i8 != has_quant)")
      e(
        f'    return boa_fail(err, "{struct.name}.{dtype_field}",'
        f' "i8 output requires exactly the quant parameters");'
      )
    else:
      raise SchemaError(f"unsupported predicate kind {kind}")


def _c_path(path: str) -> str:
  parts = path.split(".")
  return "m->" + ".".join(parts)


def _c_epilogue_code(e) -> None:
  e("BOA_UNUSED static int boa_enc_epilogue_config(const boa_epilogue_config *m, uint8_t **cur,")
  e("                                   const uint8_t *end, boa_err *err) {")
  e("  uint8_t *c = *cur;")
  e("  uint8_t enables = 0;")
  e("  size_t index;")
  e("  (void)err;")
  e("  if (m->bias.items != NULL)")
  e("    enables |= BOA_EPILOGUE_EN_BIAS;")
  e("  if (m->scale_present)")
  e("    enables |= BOA_EPILOGUE_EN_SCALE;")
  e("  if (m->relu)")
  e("    enables |= BOA_EPILOGUE_EN_RELU;")
  e("  if (m->clip_present)")
  e("    enables |= BOA_EPILOGUE_EN_CLIP;")
  e("  if (m->quant_present)")
  e("    enables |= BOA_EPILOGUE_EN_QUANT;")
  e("  c = boa_wr(c, end, m->n_cols, 2);")
  e("  c = boa_wr(c, end, enables, 1);")
  e("  for (index = 0; index < m->n_cols; index++)")
  e("    c = boa_wr(c, end, m->bias.items ? m->bias.items[index] : 0, 4);")
  e("  c = boa_wr(c, end, m->scale_present ? m->scale : 0, 4);")
  e("  c = boa_wr(c, end, m->clip_present ? m->clip.lo : 0, 4);")
  e("  c = boa_wr(c, end, m->clip_present ? m->clip.hi : 0, 4);")
  e("  c = boa_wr(c, end, m->quant_present ? m->quant.inv_scale : 0, 4);")
  e("  c = boa_wr(c, end, (uint8_t)(m->quant_present ? m->quant.zero_point : 0), 1);")
  e("  if (c == NULL)")
  e('    return boa_fail(err, "EpilogueConfig", "buffer too small");')
  e("  *cur = c;")
  e("  return 0;")
  e("}")
  e("")
  e("BOA_UNUSED static long boa_dec_epilogue_config(const uint8_t *buf, size_t *pos, size_t end,")
  e("                                   boa_epilogue_config *m, boa_err *err) {")
  e("  uint8_t enables;")
  e("  size_t index;")
  e('  if (rd_u16(buf, pos, end, &m->n_cols, "EpilogueConfig.n_cols", err) != 0)')
  e("    return -1;")
  e('  if (rd_u8(buf, pos, end, &enables, "EpilogueConfig.enables", err) != 0)')
  e("    return -1;")
  e("  m->enables = enables;")
  e("  if ((enables & BOA_EPILOGUE_RESERVED_MASK) != 0)")
  e('    return boa_fail(err, "EpilogueConfig.enables", "reserved bits must be zero");')
  e("  m->bias.count = m->n_cols;")
  e("  m->bias.items = NULL;")
  e("  if (m->n_cols > 0) {")
  e("    m->bias.items = calloc(m->n_cols, sizeof(*m->bias.items));")
  e("    if (m->bias.items == NULL)")
  e('      return boa_fail(err, "EpilogueConfig.bias", "out of memory");')
  e("  }")
  e("  for (index = 0; index < m->n_cols; index++) {")
  e('    if (rd_u32(buf, pos, end, &m->bias.items[index], "EpilogueConfig.bias[]", err) != 0)')
  e("      return -1;")
  e("    if ((enables & BOA_EPILOGUE_EN_BIAS) == 0 && m->bias.items[index] != 0)")
  e('      return boa_fail(err, "EpilogueConfig.bias", "disabled stage must serialize zeros");')
  e("  }")
  e("  if ((enables & BOA_EPILOGUE_EN_BIAS) == 0) {")
  e("    free(m->bias.items);")
  e("    m->bias.items = NULL;")
  e("    m->bias.count = 0;")
  e("  }")
  e('  if (rd_u32(buf, pos, end, &m->scale, "EpilogueConfig.scale", err) != 0)')
  e("    return -1;")
  e("  m->scale_present = (enables & BOA_EPILOGUE_EN_SCALE) != 0;")
  e("  if (!m->scale_present) {")
  e("    if (m->scale != 0)")
  e('      return boa_fail(err, "EpilogueConfig.scale", "disabled stage must serialize zeros");')
  e("    m->scale = 0;")
  e("  }")
  e('  if (rd_u32(buf, pos, end, &m->clip.lo, "EpilogueConfig.clip.lo", err) != 0)')
  e("    return -1;")
  e('  if (rd_u32(buf, pos, end, &m->clip.hi, "EpilogueConfig.clip.hi", err) != 0)')
  e("    return -1;")
  e("  m->clip_present = (enables & BOA_EPILOGUE_EN_CLIP) != 0;")
  e("  if (m->clip_present) {")
  e("    if (((m->clip.lo >> 23) & 0xffu) == 0xffu && (m->clip.lo & 0x7fffffu) != 0u)")
  e('      return boa_fail(err, "EpilogueConfig.clip.lo", "FP32 word is NaN");')
  e("    if (((m->clip.hi >> 23) & 0xffu) == 0xffu && (m->clip.hi & 0x7fffffu) != 0u)")
  e('      return boa_fail(err, "EpilogueConfig.clip.hi", "FP32 word is NaN");')
  e("    if (boa_fp32_key(m->clip.lo) > boa_fp32_key(m->clip.hi))")
  e('      return boa_fail(err, "EpilogueConfig.clip.lo", "must be <= hi as FP32 values");')
  e("  } else {")
  e("    if (m->clip.lo != 0 || m->clip.hi != 0)")
  e('      return boa_fail(err, "EpilogueConfig.clip", "disabled stage must serialize zeros");')
  e("    m->clip.lo = 0;")
  e("    m->clip.hi = 0;")
  e("  }")
  e('  if (rd_u32(buf, pos, end, &m->quant.inv_scale, "EpilogueConfig.quant.inv_scale", err) != 0)')
  e("    return -1;")
  e('  if (rd_i8(buf, pos, end, &m->quant.zero_point, "EpilogueConfig.quant.zero_point", err) != 0)')
  e("    return -1;")
  e("  m->quant_present = (enables & BOA_EPILOGUE_EN_QUANT) != 0;")
  e("  if (m->quant_present) {")
  e("    if ((m->quant.inv_scale >> 31) != 0u ||")
  e("        ((m->quant.inv_scale >> 23) & 0xffu) == 0xffu ||")
  e("        m->quant.inv_scale == 0u)")
  e('      return boa_fail(err, "EpilogueConfig.quant.inv_scale",')
  e('                          "FP32 word is not finite and strictly positive");')
  e("    /* zero_point is int8_t; the [-128,127] range is the C type itself */")
  e("  } else {")
  e("    if (m->quant.inv_scale != 0 || m->quant.zero_point != 0)")
  e('      return boa_fail(err, "EpilogueConfig.quant", "disabled stage must serialize zeros");')
  e("    m->quant.inv_scale = 0;")
  e("    m->quant.zero_point = 0;")
  e("  }")
  e("  m->relu = (enables & BOA_EPILOGUE_EN_RELU) != 0;")
  e("  return (long)(*pos);")
  e("}")
  e("")
  e("BOA_UNUSED static void boa_free_epilogue_config(boa_epilogue_config *m) {")
  e("  free(m->bias.items);")
  e("  m->bias.items = NULL;")
  e("  m->bias.count = 0;")
  e("}")
  e("")


def _c_evt_take_code(e, model: dict) -> None:
  union = model["messages"]["EVT_TAKE"].raw["union"]
  tag_enum = union["tag_type"].split(":", 1)[1]
  e("BOA_UNUSED static int boa_enc_evt_take(const boa_evt_take *m, uint8_t **cur, const uint8_t *end,")
  e("                            boa_err *err) {")
  e("  uint8_t *c = *cur;")
  e("  c = boa_wr(c, end, m->record_kind, 1);")
  e("  switch (m->record_kind) {")
  for vname, value in enum_values(model, tag_enum):
    e(f"    case {value}:")
    e(f"      if (boa_enc_{vname.lower()}(&m->rec.{vname.lower()}, &c, end, err) != 0)")
    e("        return -1;")
    e("      break;")
  e('    default: return boa_fail(err, "EVT_TAKE.record", "unknown record kind");')
  e("  }")
  e("  if (c == NULL)")
  e('    return boa_fail(err, "EVT_TAKE", "buffer too small");')
  e("  *cur = c;")
  e("  return 0;")
  e("}")
  e("")
  e("BOA_UNUSED static long boa_dec_evt_take(const uint8_t *buf, size_t *pos, size_t end,")
  e("                            boa_evt_take *m, boa_err *err) {")
  e("  uint8_t tag;")
  e('  if (rd_u8(buf, pos, end, &tag, "EVT_TAKE.record", err) != 0)')
  e("    return -1;")
  e("  m->record_kind = tag;")
  e("  switch (tag) {")
  for vname, value in enum_values(model, tag_enum):
    e(f"    case {value}:")
    e(f"      return boa_dec_{vname.lower()}(buf, pos, end, &m->rec.{vname.lower()}, err);")
  e('    default: return boa_fail(err, "EVT_TAKE.record", "unknown record kind");')
  e("  }")
  e("}")
  e("")
  e("BOA_UNUSED static void boa_free_evt_take(boa_evt_take *m) {")
  e("  switch (m->record_kind) {")
  for vname, value in enum_values(model, tag_enum):
    e(f"    case {value}:")
    e(f"      boa_free_{vname.lower()}(&m->rec.{vname.lower()});")
    e("      break;")
  e("    default:")
  e("      break;")
  e("  }")
  e("}")
  e("")



class Field:
  """One field of a struct, message payload or union variant."""

  def __init__(self, spec: dict, owner: str):
    self.owner = owner
    self.name: str = spec["name"]
    self.type: str = spec["type"]
    self.range = spec.get("range")
    self.item_range = spec.get("item_range")
    self.predicate = spec.get("predicate")
    self.count_expr = spec.get("count_expr")
    self.count_field = spec.get("count_field")
    self.role = spec.get("role")
    if self.type not in SCALARS and not self.type.startswith(("enum:", "struct:", "list:")):
      raise SchemaError(f"{owner}.{self.name}: unknown type {self.type!r}")
    if self.type.startswith("list:"):
      if bool(self.count_expr) == bool(self.count_field):
        raise SchemaError(f"{owner}.{self.name}: list needs exactly one of count_expr/count_field")
      if self.count_field is not None and self.count_field not in LIST_COUNT_FIELDS:
        raise SchemaError(f"{owner}.{self.name}: count_field must be u8 or u16")

  @property
  def kind(self) -> str:
    if self.type in SCALARS:
      return "scalar"
    if self.type.startswith("enum:"):
      return "enum"
    if self.type.startswith("struct:"):
      return "struct"
    return "list"

  @property
  def ref_name(self) -> str:
    return self.type.split(":", 1)[1]

  @property
  def elem_type(self) -> str:
    return self.type.split(":", 1)[1]

  @property
  def elem_kind(self) -> str:
    if self.elem_type in SCALARS:
      return "scalar"
    return self.elem_type.split(":", 1)[0]

  @property
  def elem_ref(self) -> str:
    return self.elem_type.split(":", 1)[1]


class Struct:
  """A struct, a message payload or a union variant record."""

  def __init__(self, name: str, raw: dict, kind: str):
    self.name = name
    self.raw = raw
    self.kind = kind  # "struct" | "message" | "variant"
    self.fields = [Field(spec, name) for spec in raw.get("fields", [])]
    self.predicates = raw.get("predicates", [])
    self.kind_id = raw.get("kind")
    self.union = raw.get("union")
    self.note = raw.get("note", "")


def parse_schema(schema: dict) -> dict:
  """Validate the schema shape and return the codegen model."""
  enums = schema["enums"]
  for ename, spec in enums.items():
    if spec.get("underlying") != "u8":
      raise SchemaError(f"enum {ename}: only a u8 underlying type is supported")
    values = spec["values"]
    if not values or len(set(values.values())) != len(values):
      raise SchemaError(f"enum {ename}: values must be nonempty and unique")
    for vname, value in values.items():
      if not isinstance(value, int) or isinstance(value, bool) or not 0 <= value <= 255:
        raise SchemaError(f"enum {ename}.{vname}: value must fit u8")

  structs = {name: Struct(name, raw, "struct") for name, raw in schema["structs"].items()}
  messages = {name: Struct(name, raw, "message") for name, raw in schema["messages"].items()}
  variants: dict[str, Struct] = {}
  for message in messages.values():
    if not message.union:
      continue
    for vname, fields in message.union["variants"].items():
      variants[vname] = Struct(vname, {"fields": fields, "note": vname}, "variant")

  known_structs = set(structs) | set(variants)
  for table, is_message in ((structs, False), (messages, True)):
    for struct in table.values():
      names = [field.name for field in struct.fields]
      if len(names) != len(set(names)):
        raise SchemaError(f"{struct.name}: duplicate field names")
      prior: set[str] = set()
      for field in struct.fields:
        _check_field_refs(field, struct, enums, known_structs, prior)
        prior.add(field.name)
      if is_message:
        if struct.kind_id is None:
          raise SchemaError(f"message {struct.name}: missing kind")
        if struct.union:
          union = struct.union
          tag_values = enums[union["tag_type"].split(":", 1)[1]]["values"]
          for vname in union["variants"]:
            if vname not in tag_values:
              raise SchemaError(f"message {struct.name}: variant {vname} is not a tag value")
          if union["tag_field"] not in names:
            raise SchemaError(f"message {struct.name}: union tag field missing")
  kinds = [message.kind_id for message in messages.values()]
  if len(kinds) != len(set(kinds)):
    raise SchemaError("message kind ids must be unique")

  order: list[str] = []
  remaining = list(structs)
  while remaining:
    progressed = False
    for name in list(remaining):
      deps = set()
      for field in structs[name].fields:
        if field.kind == "struct":
          deps.add(field.ref_name)
        elif field.kind == "list" and field.elem_kind == "struct":
          deps.add(field.elem_ref)
      if deps <= set(order):
        order.append(name)
        remaining.remove(name)
        progressed = True
    if not progressed:
      raise SchemaError(f"struct dependency cycle among {remaining}")

  _check_epilogue_shape(schema)
  return {"enums": enums, "structs": structs, "messages": messages, "variants": variants, "order": order}


def _check_epilogue_shape(schema: dict) -> None:
  epilogue = Struct("EpilogueConfig", schema["structs"].get("EpilogueConfig", {}), "struct")
  if epilogue is None:
    raise SchemaError("structs.EpilogueConfig is required")
  names = [field.name for field in epilogue.fields]
  expected = ["n_cols", "bias", "scale", "relu", "clip", "quant"]
  if names != expected:
    raise SchemaError(f"EpilogueConfig fields must be {expected}, got {names}")
  by_name = {field.name: field for field in epilogue.fields}
  if by_name["bias"].type != "list:u32" or by_name["bias"].count_expr != "n_cols":
    raise SchemaError("EpilogueConfig.bias must be list:u32 counted by n_cols")
  if by_name["scale"].type != "u32" or by_name["relu"].type != "bool8":
    raise SchemaError("EpilogueConfig.scale/relu have fixed types")
  if by_name["clip"].type != "struct:ClipPair" or by_name["quant"].type != "struct:QuantConfig":
    raise SchemaError("EpilogueConfig.clip/quant have fixed types")
  am_request = Struct("AM_REQUEST", schema["messages"]["AM_REQUEST"], "message")
  chain = [field for field in am_request.fields if field.name == "chain_config"]
  if not chain or chain[0].type != "struct:EpilogueConfig":
    raise SchemaError("AM_REQUEST.chain_config must be struct:EpilogueConfig")


def _check_field_refs(field: Field, struct: Struct, enums: dict, known_structs: set, prior: set) -> None:
  where = f"{struct.name}.{field.name}"
  if field.kind == "enum" and field.ref_name not in enums:
    raise SchemaError(f"{where}: unknown enum {field.ref_name}")
  if field.kind == "struct" and field.ref_name not in known_structs:
    raise SchemaError(f"{where}: unknown struct {field.ref_name}")
  if field.kind == "list":
    if field.count_expr is not None and field.count_expr not in prior:
      raise SchemaError(f"{where}: count_expr {field.count_expr!r} must reference a prior field")
    if field.elem_kind == "enum" and field.elem_ref not in enums:
      raise SchemaError(f"{where}: unknown list enum {field.elem_ref}")
    if field.elem_kind == "struct" and field.elem_ref not in known_structs:
      raise SchemaError(f"{where}: unknown list struct {field.elem_ref}")
    if field.elem_kind not in ("scalar", "enum", "struct"):
      raise SchemaError(f"{where}: unsupported list element")
    if field.elem_type == "bool8":
      raise SchemaError(f"{where}: bool8 list elements are not supported")
  if field.predicate not in (None, "dtype_width", "fp32_pos", "fp32_not_nan"):
    raise SchemaError(f"{where}: unknown field predicate {field.predicate!r}")



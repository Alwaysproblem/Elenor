  e("      while (i >= 0) { v = (v << 8) | (buf(pos + i) & 0xffL); i -= 1 }")
  e("      val negative = signed && (buf(pos + width - 1) & 0x80) != 0")
  e("      pos += width")
  e("      if (negative) v - (1L << (8 * width))")
  e("      else if (!signed) v & (0xffffffffffffffffL >>> (64 - 8 * width))")
  e("      else v")
  e("    }")
  e("    def u16(field: String): Int = int(2, field, signed = false).toInt")
  e("    def i16(field: String): Int = int(2, field, signed = true).toInt")
  e("    def u32(field: String): Long = int(4, field, signed = false)")

def pascal(name: str) -> str:
  """snake_case -> CamelCase (evt_take -> EvtTake); already-CamelCase stays."""
  out = []
  for part in name.split("_"):
    out.append(part.capitalize() if part.isupper() or part.islower() else part)
  return "".join(out)


def camel(name: str) -> str:
  return name.split("_")[0] + "".join(part.title() for part in name.split("_")[1:])


def scala_field_name(name: str) -> str:
  return {"final": "finalFlag"}.get(name, camel(name))


def c_sym(name: str) -> str:
  """AM_REQUEST -> am_request; ClipPair -> clip_pair (CamelCase aware)."""
  step1 = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
  return re.sub(r"(?<=[A-Z])(?=[A-Z][a-z])", "_", step1).lower()


def _chunks(items: list, size: int) -> list[list]:
  return [items[index : index + size] for index in range(0, len(items), size)]


def enum_const(enum_name: str, value_name: str) -> str:
  """AccFormat/f32 -> ACC_FORMAT_F32 (CamelCase enums become UPPER_SNAKE)."""
  prefix = re.sub(r"(?<!^)(?=[A-Z])", "_", enum_name).upper()
  return f"{prefix}_{value_name.upper()}"


def enum_values(model: dict, enum_name: str) -> list[tuple[str, int]]:
  return sorted(model["enums"][enum_name]["values"].items(), key=lambda item: item[1])


def regular_structs(model: dict) -> list[Struct]:
  """Structs without special layout, in dependency order."""
  skip = {"EpilogueConfig"}
  return [model["structs"][name] for name in model["order"] if name not in skip]


def regular_messages(model: dict) -> list[Struct]:
  """Messages without special layout, ordered by kind id."""
  skip = {"EVT_TAKE"}
  return [
    model["messages"][name]
    for name in sorted(model["messages"], key=lambda n: model["messages"][n].kind_id)
    if name not in skip
  ]


def message_names_by_kind(model: dict) -> list[str]:
  return sorted(model["messages"], key=lambda n: model["messages"][n].kind_id)


def scalar_bounds(field: Field) -> tuple[int, int]:
  return tuple(field.range or list(SCALAR_BOUNDS[field.type]))  # type: ignore[return-value]


def write_if_changed(text: str, path: Path) -> bool:
  path.parent.mkdir(parents=True, exist_ok=True)
  if path.is_file() and path.read_text(encoding="utf-8") == text:
    return False
  path.write_text(text, encoding="utf-8")
  return True



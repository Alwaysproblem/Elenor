@dataclass(frozen=True)
class SubmitStep:
  lease_handle: int
  seq: int
  mode: int
  final: bool
  transpose: int
  a: OperandView
  b: OperandView
  k_extent: int
  input_ready_tokens: tuple[EventToken, ...]
  input_usage_handles: tuple[AllocationRef, ...]
  k_mask: tuple[int, ...]
  completion_event: EventToken

  def _validate(self, _p: str = 'SubmitStep') -> None:
    _ck_range(self.lease_handle, 0, 65535, f'{_p}.lease_handle')
    _ck_range(self.seq, 0, 65535, f'{_p}.seq')
    _ck_enum(self.mode, _STEPMODE_VALID, f'{_p}.mode')
    _ck_bool(self.final, f'{_p}.final')
    _ck_enum(self.transpose, _TRANSPOSE_VALID, f'{_p}.transpose')
    self.a._validate(f'{_p}.a')
    self.b._validate(f'{_p}.b')
    _ck_range(self.k_extent, 0, 65535, f'{_p}.k_extent')
    for _item_input_ready_tokens in self.input_ready_tokens:
      _item_input_ready_tokens._validate(f'{_p}.input_ready_tokens')
    _ck_range(len(self.input_ready_tokens), 0, 255, f'{_p}.input_ready_tokens.count')
    for _item_input_usage_handles in self.input_usage_handles:
      _item_input_usage_handles._validate(f'{_p}.input_usage_handles')
    _ck_range(len(self.input_usage_handles), 0, 255, f'{_p}.input_usage_handles.count')
    _ck_items(self.k_mask, 0, 1, f'{_p}.k_mask')
    _ck_range(len(self.k_mask), 0, 65535, f'{_p}.k_mask.count')
    self.completion_event._validate(f'{_p}.completion_event')
    if any(
      _item.ctx_id == self.completion_event.ctx_id
      and _item.ctx_epoch == self.completion_event.ctx_epoch
      and _item.event_id == self.completion_event.event_id
      for _item in self.input_ready_tokens
    ):
      raise ProtocolError(f'{_p}.input_ready_tokens', 'a step must not wait on its own completion event')

  def _encode(self, _o: _Writer) -> None:
    _o.u16(self.lease_handle)
    _o.u16(self.seq)
    _o.u8(self.mode)
    _o.u8(1 if self.final else 0)
    _o.u8(self.transpose)
    self.a._encode(_o)
    self.b._encode(_o)
    _o.u16(self.k_extent)
    _o.u8(len(self.input_ready_tokens))
    for _item_input_ready_tokens in self.input_ready_tokens:
      _item_input_ready_tokens._encode(_o)
    _o.u8(len(self.input_usage_handles))
    for _item_input_usage_handles in self.input_usage_handles:
      _item_input_usage_handles._encode(_o)
    _o.u16(len(self.k_mask))
    for _item_k_mask in self.k_mask:
      _o.u8(_item_k_mask)
    self.completion_event._encode(_o)

  @classmethod
  def _decode(cls, _r: _Reader, _p: str) -> SubmitStep:
    lease_handle = _r.u16(f'{_p}.lease_handle')
    seq = _r.u16(f'{_p}.seq')
    mode = _r.u8(f'{_p}.mode')
    final = _r.u8(f'{_p}.final')
    _ck_wire_bool(final, f'{_p}.final')
    final = bool(final)
    transpose = _r.u8(f'{_p}.transpose')
    a = OperandView._decode(_r, f'{_p}.a')
    b = OperandView._decode(_r, f'{_p}.b')
    k_extent = _r.u16(f'{_p}.k_extent')
    _count = _r.u8(f'{_p}.input_ready_tokens.count')
    input_ready_tokens = tuple(
        EventToken._decode(_r, f'{_p}.input_ready_tokens[_i]')
        for _i in range(_count)
    )
    _count = _r.u8(f'{_p}.input_usage_handles.count')
    input_usage_handles = tuple(
        AllocationRef._decode(_r, f'{_p}.input_usage_handles[_i]')
        for _i in range(_count)
    )
    _count = _r.u16(f'{_p}.k_mask.count')
    k_mask = tuple(_r.u8(f'{_p}.k_mask[_i]') for _i in range(_count))
    completion_event = EventToken._decode(_r, f'{_p}.completion_event')
    value = cls(
      lease_handle=lease_handle,
      seq=seq,
      mode=mode,
      final=final,
      transpose=transpose,
      a=a,
      b=b,
      k_extent=k_extent,
      input_ready_tokens=input_ready_tokens,
      input_usage_handles=input_usage_handles,
      k_mask=k_mask,
      completion_event=completion_event,
    )
    value._validate(_p)

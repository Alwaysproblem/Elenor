def message_name(message) -> str:
  return _CLASS_NAMES[type(message)]


def _frame(kind: int, payload: bytes) -> bytes:
  header = bytes((0x42, 0x50, WIRE_VERSION, kind)) + len(payload).to_bytes(2, 'little')
  return header + payload


def encode_message(message) -> bytes:
  message._validate()
  writer = _Writer()
  message._encode(writer)
  return _frame(MESSAGE_KINDS[_CLASS_NAMES[type(message)]], writer.out())


def encode_many(messages) -> bytes:
  return b"".join(encode_message(message) for message in messages)


def decode_stream(data: bytes) -> list:
  messages = []
  pos = 0
  total = len(data)
  while pos < total:
    if total - pos < FRAME_HEADER_BYTES + 1:
      raise ProtocolError("frame", "truncated frame header")
    if data[pos : pos + 2] != MAGIC:
      raise ProtocolError("frame.magic", "bad magic")
    version = data[pos + 2]
    if version != WIRE_VERSION:
      raise ProtocolError("frame.version", f"unknown wire version {version}")
    kind = data[pos + 3]
    length = int.from_bytes(data[pos + 4 : pos + 6], 'little')
    payload_start = pos + FRAME_HEADER_BYTES + 1
    payload_end = payload_start + length
    if payload_end > total:
      raise ProtocolError("frame.length", "truncated payload")
    if kind not in _KIND_CLASSES:
      raise ProtocolError("frame.kind", f"unknown message kind {kind}")
    name = _KIND_NAMES[kind]
    reader = _Reader(data, payload_start, payload_end)
    decoder: Any = _KIND_CLASSES[kind]
    message = decoder._decode(reader, name)
    if reader.pos != payload_end:
      raise ProtocolError("frame.length", f"{name} payload has trailing bytes")
    messages.append(message)
    pos = payload_end
  return messages


def reencode(data: bytes) -> bytes:
  """Decode every frame and encode it back; byte-identical for canonical input."""
  return encode_many(decode_stream(data))

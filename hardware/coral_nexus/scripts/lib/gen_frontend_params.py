"""Generate C028's Scala consumer from the sealed C019 targets, never from defaults."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml

H = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(H / "protocol"))

import freeze_check as fc  # noqa: E402
import gen_targets as gt  # noqa: E402

OUTPUT = H / "rtl/scalar/C028TargetParams.scala"


def render() -> str:
  errors = fc.verify_seal() + gt.check()
  if errors:
    raise ValueError("C028 requires current sealed C019 targets: " + "; ".join(errors))
  targets = [yaml.safe_load(gt.OUTPUTS[name].read_text()) for name in ("cs1_c1", "cs1_c2")]
  capacities = {target["constraints"]["fetch_outstanding_per_context"] for target in targets}
  if len(capacities) != 1:
    raise ValueError("C1 and C2 must share the per-Context fetch capacity")
  capacity = capacities.pop()
  counts = ", ".join(str(target["constraints"]["context_count"]) for target in targets)
  fingerprints = ",\n".join(
    f"    {json.dumps(target['name'])} -> {json.dumps(target['fingerprints']['constraints_sha256'])}"
    for target in targets
  )
  return (
    "// GENERATED by scripts/lib/gen_frontend_params.py from sealed C019 targets.\n"
    "// This is a consumer, not an independent capacity authority.\n"
    "package coralnpu\n\n"
    "object C028TargetParams {\n"
    f"  val fetchOutstandingPerContext: Int = {capacity}\n"
    f"  val contextCounts: Seq[Int] = Seq({counts})\n"
    "  val targetFingerprints: Map[String, String] = Map(\n"
    f"{fingerprints}\n"
    "  )\n"
    "}\n"
  )


def check() -> None:
  expected = render()
  if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
    raise ValueError(f"{OUTPUT}: missing or stale C019 consumer; regenerate before building C028")


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--check", action="store_true")
  args = parser.parse_args()
  try:
    if args.check:
      check()
    else:
      gt._atomic_write(OUTPUT, render())
  except ValueError as exc:
    parser.exit(1, f"gen_frontend_params: {exc}\n")
  print("gen_frontend_params: ok")


if __name__ == "__main__":
  main()

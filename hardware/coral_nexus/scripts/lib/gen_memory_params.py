"""Generate C029's experimental RTL geometry from sealed C013/C019 inputs."""

from __future__ import annotations

import argparse
import hashlib
import json
import math
import re
import sys
from pathlib import Path
from typing import Any

import yaml

H = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(H / "scripts"))
sys.path.insert(0, str(H / "protocol"))

import derive_w4_bounds as dw  # noqa: E402
import freeze_check as fc  # noqa: E402
import gen_targets as gt  # noqa: E402

OUTPUT = H / "rtl/memory/c029_params_pkg.sv"


def _integer(value: Any, name: str, minimum: int = 1) -> int:
  if isinstance(value, bool) or not isinstance(value, (int, float)):
    raise ValueError(f"{name}: expected a sourced integer")
  if not math.isfinite(value) or int(value) != value or value < minimum:
    raise ValueError(f"{name}: expected an integer >= {minimum}, got {value}")
  if value >= 1 << 32:
    raise ValueError(f"{name}: exceeds SystemVerilog int unsigned geometry storage")
  return int(value)


def parameters() -> dict[str, Any]:
  errors = fc.verify_seal() + gt.check()
  if errors:
    raise ValueError("C029 requires current sealed C013/C019 inputs: " + "; ".join(errors))
  constraints = dw.load_constraints()
  _derived, errors = dw.validate_constraints(constraints)
  if errors:
    raise ValueError("C029 memory constraints: " + "; ".join(errors))
  values = dw.bounds_env(constraints)
  names = {
    "BANK_COUNT": "tile_l1_banks",
    "BANK_BYTES": "l1_per_bank_bytes",
    "SYSTEM_RESERVED_BYTES": "system_reserved_spm_per_bank",
    "SLOT_COUNT": "frame_slot_budget",
    "DATA_BYTES": "l1_bank_bytes_per_cycle",
    "BANK_LATENCY_CYCLES": "l1_access_latency_cycles",
    "MSHR_ENTRIES": "l1_mshr_entries",
    "LINE_BYTES": "cache_line_bytes",
  }
  result: dict[str, Any] = {
    key: _integer(values[source], source, 0 if key == "BANK_LATENCY_CYCLES" else 1)
    for key, source in names.items()
  }
  modes = sorted(
    int(match[1])
    for name in values
    if (match := re.fullmatch(r"spm_bytes_per_bank_mode(\d+)", name))
  )
  if not modes or modes != list(range(len(modes))):
    raise ValueError("C029 requires a contiguous sourced SPM profile table")
  result["SPM_BYTES_PER_BANK"] = [
    _integer(values[f"spm_bytes_per_bank_mode{mode}"], f"SPM profile {mode}") for mode in modes
  ]
  cache_modes = sorted(
    int(match[1])
    for name in values
    if (match := re.fullmatch(r"cache_bytes_per_bank_mode(\d+)", name))
  )
  if cache_modes != modes:
    raise ValueError("C030 requires a cache profile table matching the SPM profile table")
  result["CACHE_BYTES_PER_BANK"] = [
    int(values[f"cache_bytes_per_bank_mode{mode}"]) for mode in cache_modes
  ]
  for spm, cache in zip(result["SPM_BYTES_PER_BANK"], result["CACHE_BYTES_PER_BANK"], strict=True):
    if cache < 0 or cache % result["LINE_BYTES"] or spm + cache != result["BANK_BYTES"]:
      raise ValueError("C030 cache/SPM partition is not line-aligned or does not fill the bank")
  result["PROFILE_COUNT"] = len(modes)
  for size in result["SPM_BYTES_PER_BANK"]:
    if not result["SYSTEM_RESERVED_BYTES"] <= size <= result["BANK_BYTES"]:
      raise ValueError("C029 SPM/reserved partition escapes a physical bank")
  if result["BANK_BYTES"] % result["DATA_BYTES"]:
    raise ValueError("C029 bank geometry is not an integral number of sourced data beats")
  targets = [yaml.safe_load(gt.OUTPUTS[name].read_text()) for name in ("cs1_c1", "cs1_c2")]
  for index, target in enumerate(targets, start=1):
    capacity = target["constraints"]
    if capacity["system_reserved_spm_per_bank"] != result["SYSTEM_RESERVED_BYTES"] or capacity[
      "user_spm_per_bank"
    ] != result["SPM_BYTES_PER_BANK"][0] - result["SYSTEM_RESERVED_BYTES"]:
      raise ValueError(f"{target['name']}: C013/C019 per-bank capacities disagree")
    result[f"C{index}_CONTEXTS"] = _integer(capacity["context_count"], "context_count")
    result[f"C{index}_TARGET_SHA256"] = target["fingerprints"]["constraints_sha256"]
  decisions = yaml.safe_load(fc.W4_DECISIONS.read_text())["decisions"]
  if fc.open_budgets():
    raise ValueError("C031 requires closed sealed W4 capacity decisions")
  result["LSU_CREDIT_CAP"] = _integer(
    decisions["per_ctx_outstanding_credit_cap"]["value"], "per_ctx_outstanding_credit_cap"
  )
  # Retain fill buffers until every possible LSU record has consumed its
  # waiter. This is not the independent early-release response-record pool.
  result["LSU_MSHR_WAITERS"] = _integer(
    result["C2_CONTEXTS"] * result["LSU_CREDIT_CAP"], "bounded retained LSU waiters"
  )
  result["C013_SHA256"] = hashlib.sha256(dw.CONTRACT.read_bytes()).hexdigest()
  result["SEAL_SHA256"] = hashlib.sha256((H / "protocol/PROTOCOL_FREEZE.json").read_bytes()).hexdigest()
  return result


def render() -> str:
  values = parameters()
  lines = [
    "// GENERATED by scripts/lib/gen_memory_params.py; do not edit.",
    "// Experimental C013/C019 model geometry, not a silicon SRAM/PPA freeze.",
    "// No silicon identity or epoch widths are inferred from transport containers.",
    "`timescale 1ns/1ps",
    "package c029_params_pkg;",
  ]
  for name, value in values.items():
    if name in ("SPM_BYTES_PER_BANK", "CACHE_BYTES_PER_BANK"):
      continue
    if isinstance(value, str):
      lines.append(f"  localparam string {name} = {json.dumps(value)};")
    else:
      lines.append(f"  localparam int unsigned {name} = {value};")
  sizes = ", ".join(str(value) for value in values["SPM_BYTES_PER_BANK"])
  cache_sizes = ", ".join(str(value) for value in values["CACHE_BYTES_PER_BANK"])
  lines.extend(
    [
      f"  localparam int unsigned SPM_BYTES_PER_BANK [PROFILE_COUNT] = '{{{sizes}}};",
      f"  localparam int unsigned CACHE_BYTES_PER_BANK [PROFILE_COUNT] = '{{{cache_sizes}}};",
      "endpackage",
      "",
    ]
  )
  return "\n".join(lines)


def check() -> None:
  expected = render()
  if not OUTPUT.is_file() or OUTPUT.read_text() != expected:
    raise ValueError(f"{OUTPUT}: missing or stale C013/C019 consumer; regenerate before building C029")


def main() -> None:
  parser = argparse.ArgumentParser(description=__doc__)
  parser.add_argument("--check", action="store_true")
  args = parser.parse_args()
  try:
    if args.check:
      check()
    else:
      gt._atomic_write(OUTPUT, render())
  except (ValueError, dw.BoundsError) as exc:
    parser.exit(1, f"gen_memory_params: {exc}\n")
  print("gen_memory_params: ok")


if __name__ == "__main__":
  main()

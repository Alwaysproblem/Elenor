"""Generate the software-managed AM Matmul fixture and its input bytes.

The committed fixture is A[64,128]bf16 x B[128,256]bf16 -> C[64,256]f32 with
the reduction split into two 64-deep steps.  A is block-packed as
A[2,64,64] and B as B[2,64,256] so each step is one contiguous L2 subview.

The generator is deterministic: regenerating the fixture and its inputs is
byte-identical.  Read bindings are seeded with small normal BF16 values;
write-only outputs are not seeded.
"""

from __future__ import annotations

import argparse
import struct
from pathlib import Path

from transformer_common import write_workload

from pipeline_validator.dialects.elenor import NestContextOp, NestGlobalMemref, NexusProgramOp
from pipeline_validator.workload_ir import load_workload_ir, parse_workload_ir

REPO = Path(__file__).resolve().parents[2]
WORKLOADS = REPO / "examples" / "workloads"
INPUT_ROOT = WORKLOADS / "boa_am_inputs"

HEADER = [
  "Software-managed AM Matmul: A[64,128]bf16 x B[128,256]bf16 -> C[64,256]f32.",
  "",
  "K=128 is split into two 64-deep steps: the first step INITs the AM",
  "accumulator, the second uses `accumulate output` to add the last product,",
  "convert to the bound f32 L1 output, and release the AM slot automatically.",
  "A is block-packed [2,64,64] and B [2,64,256] so both K-step inputs are",
  "contiguous L2 subviews.  The 64x256 f32 AM slot needs exactly 64 KiB.",
  "",
  "Generated by examples/generators/generate_boa_am_matmul.py.",
  "Run: bash examples/run.sh boa-am-matmul",
]

SOURCE = '''builtin.module {
  tile.program @boa_am_mm(
      %task : !nest.task,
      %a_l2 : !nest.l2_buffer<2x64x64xbf16>,
      %b_l2 : !nest.l2_buffer<2x64x256xbf16>,
      %c_l2 : !nest.l2_buffer<64x256xf32>)
                resource_contract = #tile.resources<allowed_profiles = [0, 1, 2],
          tile_l1_spm_bytes_per_context = 147456> {
    %a0_v = tile.subview %a_l2
        offsets = [0, 0, 0] sizes = [1, 64, 64] strides = [1, 1, 1]
        : !nest.l2_view<1x64x64xbf16>
    %a1_v = tile.subview %a_l2
        offsets = [1, 0, 0] sizes = [1, 64, 64] strides = [1, 1, 1]
        : !nest.l2_view<1x64x64xbf16>
    %b0_v = tile.subview %b_l2
        offsets = [0, 0, 0] sizes = [1, 64, 256] strides = [1, 1, 1]
        : !nest.l2_view<1x64x256xbf16>
    %b1_v = tile.subview %b_l2
        offsets = [1, 0, 0] sizes = [1, 64, 256] strides = [1, 1, 1]
        : !nest.l2_view<1x64x256xbf16>
    %c_v = tile.subview %c_l2
        offsets = [0, 0] sizes = [64, 256] strides = [1, 1]
        : !nest.l2_view<64x256xf32>
    %a0 = tile.alloc shape = [64, 64] dtype = "bf16"
        alignment = 256 : !tile.l1_buffer<64x64xbf16>
    %a1 = tile.alloc shape = [64, 64] dtype = "bf16"
        alignment = 256 : !tile.l1_buffer<64x64xbf16>
    %b0 = tile.alloc shape = [64, 256] dtype = "bf16"
        alignment = 256 : !tile.l1_buffer<64x256xbf16>
    %b1 = tile.alloc shape = [64, 256] dtype = "bf16"
        alignment = 256 : !tile.l1_buffer<64x256xbf16>
    %out = tile.alloc memory_space = "l1" shape = [64, 256] dtype = "f32"
        alignment = 256 : !tile.l1_buffer<64x256xf32>
    %acc = tile.alloc memory_space = "am" logical_slot = 0 output(%out)
        shape = [64, 256] dtype = "f32" alignment = 256
        : !tile.am_buffer<64x256xf32>
    %la0 = tile.load.async %a0_v into %a0 : !tile.event<"la0">
    %lb0 = tile.load.async %b0_v into %b0 : !tile.event<"lb0">
    %la1 = tile.load.async %a1_v into %a1 : !tile.event<"la1">
    %lb1 = tile.load.async %b1_v into %b1 : !tile.event<"lb1">
    tile.await %la0, %lb0
    %k0 = tile.boa.async "matmul" ins(%a0, %b0) outs(%out) acc(%acc)
        m = 64 n = 256 k = 64 seq = 0
        : !tile.event<"k0">
    tile.await %la1, %lb1
    tile.signal input_released(%task)
    tile.await %k0
    %done = tile.boa.async "matmul" ins(%a1, %b1) outs(%out) acc(%acc)
        m = 64 n = 256 k = 64 seq = 1 accumulate output
        : !tile.event<"done">
    tile.await %done
    tile.free %a0
    tile.free %a1
    tile.free %b0
    tile.free %b1
    %stored = tile.store.async %out into %c_v : !tile.event<"stored">
    tile.await %stored
    tile.signal output_ready(%task)
    tile.return
  }

  nest.context @boa_am_ctx(
      %A : !nest.global_memref<2x64x64xbf16>,
      %B : !nest.global_memref<2x64x256xbf16>,
      %C : !nest.global_memref<64x256xf32>)
      placement = 1
                resource_contract = #nest.context_resources<l2_mode = 0,
          allowed_profiles = [0, 1, 2], logical_tasks = 1, l2_spm_bytes = 147456,
          requested_contexts_per_tile = 1> {
    %a_blk = nest.subview %A
        offsets = [0, 0, 0] sizes = [2, 64, 64] strides = [1, 1, 1]
        : !nest.global_view<2x64x64xbf16>
    %b_blk = nest.subview %B
        offsets = [0, 0, 0] sizes = [2, 64, 256] strides = [1, 1, 1]
        : !nest.global_view<2x64x256xbf16>
    %c_blk = nest.subview %C
        offsets = [0, 0] sizes = [64, 256] strides = [1, 1]
        : !nest.global_view<64x256xf32>
    %a_l2 = nest.alloc slot = "a" role = "in"
        shape = [2, 64, 64] dtype = "bf16" alignment = 256
        : !nest.l2_buffer<2x64x64xbf16>
    %b_l2 = nest.alloc slot = "b" role = "in"
        shape = [2, 64, 256] dtype = "bf16" alignment = 256
        : !nest.l2_buffer<2x64x256xbf16>
    %c_l2 = nest.alloc slot = "c" role = "out"
        shape = [64, 256] dtype = "f32" alignment = 256
        : !nest.l2_buffer<64x256xf32>
    %a_pref = nest.dma.prefetch.async %a_blk into %a_l2
        : !nest.event<"a_pref">
    %b_pref = nest.dma.prefetch.async %b_blk into %b_l2
        : !nest.event<"b_pref">
    %tasks = nest.task.range from = 0 to = 1 : !nest.task_range
    %grid, %read, %ready =
        nest.dispatch.tasks.async @boa_am_mm l1_mode = 0 context = 0
        tasks(%tasks) globals()
        bindings(%a_l2, %b_l2, %c_l2) ins(%a_l2, %b_l2) outs(%c_l2)
        signal_policy {
          input_released = #nest.aggregate<all_tasks>,
          output_ready = #nest.aggregate<all_tasks>
        }
        depends_on(%a_pref, %b_pref)
        : (!nest.event<"grid">, !nest.event<"read">, !nest.event<"ready">)
    %c_store = nest.dma.store.async %c_l2 into %c_blk
        depends_on(%ready) : !nest.event<"c_store">
    nest.release %a_l2 depends_on(%read, %a_pref)
    nest.release %b_l2 depends_on(%read, %b_pref)
    nest.release %c_l2 depends_on(%c_store)
    nest.await %grid, %c_store
    nest.return
  }

  nexus.program @boa_am_matmul(
      %A : !nest.global_memref<2x64x64xbf16>,
      %B : !nest.global_memref<2x64x256xbf16>,
      %C : !nest.global_memref<64x256xf32>) {
    %done = nexus.submit_context.async @boa_am_ctx(%A, %B, %C)
        : !nexus.event<"done">
    nexus.await %done
    nexus.return
  }
}
'''

DTYPE_BYTES = {"bf16": 2, "f32": 4, "i8": 1, "i32": 4}


def _shape_size(memref_type) -> int:
    size = 1
    for dim in memref_type.dims:
        size *= int(dim.value.data)
    return size * DTYPE_BYTES[memref_type.dtype.data]


def _seed_bf16(count: int, modulus: int = 7) -> bytes:
    values = bytearray()
    for index in range(count):
        value = float((index * 3) % modulus - (modulus // 2))
        bits = struct.unpack("<I", struct.pack("<f", value))[0]
        rounded = (bits + 0x7FFF + ((bits >> 16) & 1)) >> 16
        values += struct.pack("<H", rounded & 0xFFFF)
    return bytes(values)


def _entry_bindings(path: Path) -> list[tuple[str, NestGlobalMemref]]:
    module = load_workload_ir(path)
    entry = next(
        (op for op in module.body.block.ops if isinstance(op, NexusProgramOp)), None
    ) or next((op for op in module.body.block.ops if isinstance(op, NestContextOp)), None)
    if entry is None:
        raise ValueError(f"{path}: no nexus.program or nest.context entry")
    bindings: list[tuple[str, NestGlobalMemref]] = []
    for arg in entry.body.block.args:
      if isinstance(arg.type, NestGlobalMemref):
        bindings.append((arg.name_hint or "", arg.type))
    return bindings


def _write_binding_inputs(path: Path) -> int:
    stem = path.stem
    written = 0
    for name, memref_type in _entry_bindings(path):
        if name in ("C", "S") or name.startswith("output"):
            continue
        element_bytes = DTYPE_BYTES[memref_type.dtype.data]
        elements = _shape_size(memref_type) // element_bytes
        data = _seed_bf16(elements)
        target = INPUT_ROOT / stem / f"{name}.bin"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        written += 1
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--existing",
        action="store_true",
        help="also seed inputs for the already-committed typed Matmul fixtures",
    )
    args = parser.parse_args()

    fixture = write_workload(
        WORKLOADS / "boa_am_matmul.mlir", HEADER, parse_workload_ir(SOURCE)
    )
    print(f"wrote {fixture.relative_to(REPO)}")

    seed_targets = [fixture]
    if args.existing:
        seed_targets.extend(
            WORKLOADS / name
            for name in (
                "matmul_2048x512x64_boa256x256x32.mlir",
                "matmul_pow_parallel.mlir",
                "matmul_pow_free_slot.mlir",
                "matmul_pow_data_dep.mlir",
                "matmul17_pow_tail_overlap.mlir",
                "matmul_splitk_pipeline.mlir",
                "matmul_splitk_multicontext_pipeline.mlir",
            )
        )
    count = 0
    for target in seed_targets:
        count += _write_binding_inputs(target)
    print(f"wrote {count} input files under {INPUT_ROOT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
